// Command gen regenerates internal/sds/schema_embed_bindings_test.go: the
// drift guard's denominator, derived from the embedded IDLs instead of a
// hand-kept list.
//
//	go generate ./sdn-server/internal/sds/...
//
// Every embedded schema whose root_type has a generated binding in the pinned
// spacedatastandards.org/lib/go (vendored at third_party/spacedatastandards-go)
// is drift-guarded. The rest are waived with the measured reason: no
// root_type (an include-only IDL) or no published binding (an SDN-local
// schema). TestDriftGuardCoverageIsDeclared fails on any embed in neither
// list, so a new embed without a regeneration cannot pass.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const modulePath = "github.com/DigitalArsenal/spacedatastandards.org/lib/go"

var rootTypeRe = regexp.MustCompile(`(?m)^\s*root_type\s+([A-Za-z_][A-Za-z0-9_]*)\s*;`)

func main() {
	schemaDir := flag.String("schemas", "schemas", "directory holding the embedded .fbs IDLs")
	bindingDir := flag.String("bindings", "../../third_party/spacedatastandards-go", "vendored lib/go bindings")
	out := flag.String("out", "schema_embed_bindings_test.go", "generated Go file to write")
	flag.Parse()

	entries, err := os.ReadDir(*schemaDir)
	if err != nil {
		fatal(err)
	}
	type guard struct{ file, pkg, root string }
	var guards []guard
	waived := map[string]string{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".fbs") {
			continue
		}
		idl, err := os.ReadFile(filepath.Join(*schemaDir, name))
		if err != nil {
			fatal(err)
		}
		pkg := strings.TrimSuffix(name, ".fbs")
		m := rootTypeRe.FindSubmatch(idl)
		if m == nil {
			waived[name] = "no root_type: an include-only IDL"
			continue
		}
		root := string(m[1])
		src, err := os.ReadFile(filepath.Join(*bindingDir, pkg, root+".go"))
		if err != nil || !bytes.Contains(src, []byte("type "+root+" struct")) {
			waived[name] = "no published lib/go binding: an SDN-local schema"
			continue
		}
		guards = append(guards, guard{name, pkg, root})
	}
	sort.Slice(guards, func(i, j int) bool { return guards[i].file < guards[j].file })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/sds/gen; DO NOT EDIT.\n// Regenerate with: go generate ./sdn-server/internal/sds/...\n\npackage sds\n\nimport (\n")
	for _, g := range guards {
		fmt.Fprintf(&b, "\tb%s %q\n", g.pkg, modulePath+"/"+g.pkg)
	}
	b.WriteString(")\n\n// driftGuardedSchemas is every embedded standard with a linked binding.\nvar driftGuardedSchemas = []struct {\n\tfile    string\n\tbinding interface{}\n}{\n")
	for _, g := range guards {
		fmt.Fprintf(&b, "\t{%q, &b%s.%s{}},\n", g.file, g.pkg, g.root)
	}
	b.WriteString("}\n\n// unguardedEmbeddedSchemas are the embeds no linked binding can check.\nvar unguardedEmbeddedSchemas = map[string]bool{\n")
	names := make([]string, 0, len(waived))
	for name := range waived {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: true, // %s\n", name, waived[name])
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("drift guard: %d guarded, %d waived -> %s\n", len(guards), len(waived), *out)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
