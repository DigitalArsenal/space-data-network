func rnd(n int) []byte {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return b
}

func newEncKeys() encKeys {
	k := encKeys{KMFKey: rnd(32), FieldKey: rnd(32), RecipPriv: rnd(32), StorePriv: rnd(32)}
	k.RecipPub, _ = curve25519.X25519(k.RecipPriv, curve25519.Basepoint)
	k.StorePub, _ = curve25519.X25519(k.StorePriv, curve25519.Basepoint)
	return k
}

func (k encKeys) MarshalJSON() ([]byte, error) {
	return json.Marshal(map[string]string{
		"note":                      "THROWAWAY TEST KEYS generated by format4proof DriveEncryptedFields (encfields.go, crypto/rand); not credentials",
		"kmf_key_hex":               hex.EncodeToString(k.KMFKey),
		"field_key_hex":             hex.EncodeToString(k.FieldKey),
		"recipient_x25519_priv_hex": hex.EncodeToString(k.RecipPriv),
		"recipient_x25519_pub_hex":  hex.EncodeToString(k.RecipPub),
		"store_x25519_priv_hex":     hex.EncodeToString(k.StorePriv),
		"store_x25519_pub_hex":      hex.EncodeToString(k.StorePub),
	})
}

// provisionStoreKey writes the store's field-encryption identity (SDN reads
// it when present, storage/field_encryption.go) before the first open.
func provisionStoreKey(dir string, k encKeys) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	b, _ := json.MarshalIndent(map[string]string{"public_key_hex": hex.EncodeToString(k.StorePub), "private_key_hex": hex.EncodeToString(k.StorePriv)}, "", "  ")
	return os.WriteFile(filepath.Join(dir, "field-encryption-identity.json"), b, 0o600)
}

