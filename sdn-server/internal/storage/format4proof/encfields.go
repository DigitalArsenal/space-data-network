// walkStreams walks every P/<TYPE>/*.fsdata of a format-4 store as
// [u32 LE size][bytes] frames and classifies each frame.
func (e *encRun) walkStreams(store string) ([]Row, []string) {
	var rows []Row
	var probs []string
	root := filepath.Join(store, "fsql4", "P")
	types, _ := os.ReadDir(root)
	for _, td := range types {
		files, _ := os.ReadDir(filepath.Join(root, td.Name()))
		for _, f := range files {
			if !strings.HasSuffix(f.Name(), ".fsdata") {
				continue
			}
			path := filepath.Join(root, td.Name(), f.Name())
			data, err := os.ReadFile(path)
			if err != nil {
				probs = append(probs, err.Error())
				continue
			}
			var frames, flat, sealedN, opened, written, cipherOK int
			at := 0
			for at < len(data) {
				if len(data)-at < 4 {
					probs = append(probs, fmt.Sprintf("%s: torn size prefix at %d", path, at))
					break
				}
				n := int(binary.LittleEndian.Uint32(data[at:]))
				if len(data)-at-4 < n {
					probs = append(probs, fmt.Sprintf("%s: frame at %d runs past EOF", path, at))
					break
				}
				fr := data[at+4 : at+4+n]
				frames++
				switch {
				case encfield.IsSealed(fr) || encfield.IsSealedForRecipients(fr):
					sealedN++
					plain, was, err := encfield.Open(td.Name(), fr, e.keys.StorePriv, storeFieldEncryptionContext)
					if err != nil || !was {
						probs = append(probs, fmt.Sprintf("%s: sealed frame at %d does not open with the store key: %v", path, at, err))
						break
					}
					opened++
					if w := e.byCID[storage.ComputeCID(plain)]; w != nil && bytes.Equal(plain, w.Bytes) {
						written++
						// The envelope's record keeps the client's ciphertext
						// under the store's layer: neither the client
						// ciphertext nor the plaintext is in the frame.
						for _, ef := range w.Fields {
							if bytes.Contains(fr, ef.Cipher) || bytes.Contains(fr, ef.Plain) {
								probs = append(probs, fmt.Sprintf("%s: sealed frame at %d holds %s in the clear", path, at, ef.Name))
							}
						}
						cipherOK++
					} else {
						probs = append(probs, fmt.Sprintf("%s: sealed frame at %d opens to a record this driver did not write", path, at))
					}
				default:
					flat++
					w := e.byCID[storage.ComputeCID(fr)]
					if w == nil {
						probs = append(probs, fmt.Sprintf("%s: frame at %d is not a record this driver wrote (cid %s)", path, at, storage.ComputeCID(fr)))
						break
					}
					written++
					if len(fr) < 8 || string(fr[4:8]) != "$"+strings.TrimSuffix(w.Type, ".fbs") {
						probs = append(probs, fmt.Sprintf("%s: frame at %d has file identifier %q", path, at, fr[4:8]))
					}
					good := true
					for _, ef := range w.Fields {
						if !bytes.Contains(fr, ef.Cipher) || (len(ef.Plain) >= 4 && bytes.Contains(fr, ef.Plain)) {
							good = false
							probs = append(probs, fmt.Sprintf("%s: frame at %d: %s is not its ciphertext", path, at, ef.Name))
						}
					}
					if good {
						cipherOK++
					}
				}
				at += 4 + n
			}
			rows = append(rows, ValueRow("file", strings.TrimPrefix(path, store+"/"), "bytes", strconv.Itoa(len(data)), "frames", strconv.Itoa(frames),
				"flatbuffer_frames", strconv.Itoa(flat), "sealed_frames", strconv.Itoa(sealedN), "sealed_opened_with_store_key", strconv.Itoa(opened),
				"frames_of_written_records", strconv.Itoa(written), "encrypted_fields_ciphertext", strconv.Itoa(cipherOK), "ends_at_eof", strconv.FormatBool(at == len(data))))
		}
	}
	return rows, probs
}

// needle is one recognizable encoding of a plaintext (or, for a field SDN
// seals at rest, of the client ciphertext SDN received).
type needle struct {
	What string
	B    []byte
}

func encodings(what string, b []byte) []needle {
	out := []needle{{what + " raw", b}, {what + " hex", []byte(hex.EncodeToString(b))}, {what + " HEX", []byte(strings.ToUpper(hex.EncodeToString(b)))},
		{what + " base64", []byte(strings.TrimRight(base64.StdEncoding.EncodeToString(b), "="))},
		{what + " base64url", []byte(strings.TrimRight(base64.URLEncoding.EncodeToString(b), "="))}}
	return out
}

// needles are every plaintext's encodings, the scalar ones as their decimal
// text too, and the client ciphertext of every field SDN seals at rest (KMF).
func (e *encRun) needles() []needle {
	var out []needle
	for _, c := range e.classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				id := fmt.Sprintf("%s %s plaintext", w.CID[:16], f.Name)
				out = append(out, encodings(id, f.Plain)...)
				switch f.Kind {
				case "u32":
					v := binary.LittleEndian.Uint32(f.Plain)
					out = append(out, needle{id + " BE", binary.BigEndian.AppendUint32(nil, v)}, needle{id + " decimal", []byte(strconv.FormatUint(uint64(v), 10))})
				case "f64":
					v := math.Float64frombits(binary.LittleEndian.Uint64(f.Plain))
					out = append(out, needle{id + " BE", binary.BigEndian.AppendUint64(nil, math.Float64bits(v))},
						needle{id + " %.17g", []byte(strconv.FormatFloat(v, 'g', 17, 64))}, needle{id + " %g", []byte(strconv.FormatFloat(v, 'g', -1, 64))})
				}
				if w.Type == "KMF.fbs" {
					out = append(out, encodings(fmt.Sprintf("%s %s client-ciphertext (sealed at rest)", w.CID[:16], f.Name), f.Cipher)...)
				}
			}
		}
	}
	return out
}

// grepStore searches every file under dir for every needle.
func grepStore(dir string, needles []needle) (files int, scanned int64, hits []string) {
	_ = filepath.Walk(dir, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			hits = append(hits, "read "+p+": "+err.Error())
			return nil
		}
		files++
		scanned += int64(len(b))
		for _, n := range needles {
			if len(n.B) >= 4 && bytes.Contains(b, n.B) {
				hits = append(hits, fmt.Sprintf("%s in %s", n.What, strings.TrimPrefix(p, dir+"/")))
			}
		}
		return nil
	})
	return files, scanned, hits
}

// fileKinds counts a store's files by kind (suffix).
func fileKinds(dir string) map[string]int {
	out := map[string]int{}
	_ = filepath.Walk(dir, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}
		n := filepath.Base(p)
		k := filepath.Ext(n)
		for _, suf := range []string{"-wal", "-shm", ".fsdata", ".db", ".fts", ".idx", ".spec"} {
			if strings.HasSuffix(n, suf) {
				k = suf
			}
		}
		out[k]++
		return nil
	})
	return out
}

// ---- comparison ------------------------------------------------------------

// encRulings are the contract's accepted differences the comparison applies,
// each by name:
//   - C-9: a relation's meta columns _rowid and _offset are each format's own
//     (format 4: _rowid = seq, _offset = 0): dropped from SELECT * rows;
//   - C-41 N3: format 1's cursor pages list tagged records before untagged
//     ones, format 4 pages by seq: cursor pages (SCAN cursor and refs, a
//     search by cursor) compare as sets;
//   - C-39 E7: a lane page is ordered by the record timestamp alone, so one
//     batch's records tie: lane pages compare as sets;
//   - R18 (r18Accepted): format 1's epoch stream ranks by
//     USER_DEFINED_EPOCH_TIMESTAMP, format 4 by the EPOCH rule, so a record
//     whose EPOCH the client encrypted (no epoch on format 4) is in format
//     1's stream only: exactly those records' frames may be format 1's alone;
//   - C-48 (a) (encFastPathShadow): format 1's SandboxedSelect fast path
//     answers `SELECT * FROM "<TYPE>@<source>"` from the type's whole record
//     list (its shared store's), every row named <TYPE>@<source>; format 4
//     answers the source's records: every format-4 row must be one of
//     format 1's, and the run reports the rows format 1 adds;
//   - C-48 (b) (encF1NUL): format 1 reads text out of its engine as a C
//     string (flatsql_result_cell_string), so a string holding a NUL byte
//     (a client's ciphertext may) ends at that byte in its SandboxedSelect
//     cells and its point-profile EPOCH entity keys; format 4 keeps the
//     whole string. Values on those surfaces are compared cut at their first
//     NUL on both arms, and the run reports the calls that needed it.
var encSetCalls = []string{"SCAN cursor ", "SCAN refs ", "LANE ", "FTS "}

// encF1NUL cuts at the first NUL the values format 1 may read as C strings
// (C-48 (b)): every text cell of a SandboxedSelect ("SELECT " calls) and an
// EPOCH read's entity key. Values arrive as text or "hex:" + hex (not
// UTF-8). It returns the rows and how many values it cut.
func encF1NUL(name string, b []Row) ([]Row, int) {
	sel, epoch := strings.HasPrefix(name, "SELECT "), strings.HasPrefix(name, "EPOCH ")
	if !sel && !epoch {
		return b, 0
	}
	n := 0
	out := make([]Row, len(b))
	for i, r := range b {
		out[i] = append(Row(nil), r...)
		for j, f := range out[i] {
			if (epoch && f.N != "entity") || (sel && (f.N == "columns" || f.N == "truncated")) {
				continue
			}
			raw := []byte(f.V)
			if h, ok := strings.CutPrefix(f.V, "hex:"); ok {
				if d, err := hex.DecodeString(h); err == nil {
					raw = d
				}
			}
			cut, _, found := bytes.Cut(raw, []byte{0})
			if !found {
				continue
			}
			n++
			if v := string(cut); utf8.ValidString(v) {
				out[i][j].V = v
			} else {
				out[i][j].V = "hex:" + hex.EncodeToString(cut)
			}
		}
	}
	if sel && n > 0 && len(out) > 1 {
		out = append(out[:1:1], sortRows(out[1:])...) // selSQL sorts the body rows
	}
	return out, n
}

// encFastPathShadow is C-48 (a) above: ok when name is a
// SandboxedSelect `SELECT * FROM "<TYPE>@<source>"`, the headers (columns,
// truncated) are equal and every row of b (format 4) is one of a's (format
// 1's); extra is how many rows format 1 adds.
func encFastPathShadow(name string, a, b []Row) (extra int, ok bool) {
	if !strings.HasPrefix(name, "SELECT ") || !encSelectStar(name) || !strings.Contains(name, "@") || len(a) == 0 || len(b) == 0 ||
		strictText(a[0]) != strictText(b[0]) {
		return 0, false
	}
	held := map[string]int{}
	for _, r := range a[1:] {
		held[strictText(r)]++
	}
	for _, r := range b[1:] {
		if held[strictText(r)] == 0 {
			return 0, false
		}
		held[strictText(r)]--
	}
	return len(a) - len(b), true
}

// encSelectStar reports a call whose statement is a SELECT * (C-9's rows).
func encSelectStar(name string) bool {
	return strings.Contains(strings.ToLower(strings.Join(strings.Fields(name), " ")), "select * from")
}

func encNormalize(name string, rows []Row) []Row {
	out := make([]Row, 0, len(rows))
	for _, r := range rows {
		n := Row{}
		for _, f := range r {
			if f.N == "~err_text" || f.N == "~seconds" {
				continue
			}
			if encSelectStar(name) && (f.N == "_offset" || f.N == "_rowid") {
				continue
			}
			n = append(n, f)
		}
		out = append(out, n)
	}
	for _, p := range encSetCalls {
		if strings.HasPrefix(name, p) {
			return sortRows(out)
		}
	}
	return out
}

// encR18 is the R18 ruling on an OMM epoch stream: format 1's rows that
// format 4 lacks and that are frames of records whose EPOCH the client
// encrypted are dropped (returned as the accepted rows).
func encR18(name string, a, b []Row, encEpoch map[string]bool) ([]Row, int) {
	if !strings.HasPrefix(name, "EPOCH STREAM OMM.fbs@") {
		return a, 0
	}
	inB := map[string]bool{}
	for _, r := range b {
		inB[r.Get("h")] = true
	}
	var out []Row
	n := 0
	for _, r := range a {
		if h := r.Get("h"); encEpoch[h] && !inB[h] {
			n++
			continue
		}
		out = append(out, r)
	}
	return out, n
}

// encCompared is compareCalls' answer: the differences outside encRulings,
// the rows R18 accepted, and the rows format 1's fast path adds to a feed
// relation's SELECT * (C-48 (a)) and the values format 1 cut at a NUL
// (C-48 (b)), per call.
type encCompared struct {
	Diffs  []string       `json:"diffs"`
	R18    int            `json:"r18_rows"`
	Shadow map[string]int `json:"fastpath_shadow_rows,omitempty"`
	NUL    map[string]int `json:"f1_nul_values,omitempty"`
}

// compareCalls compares b's answers with a's (format 1's) under encRulings.
func compareCalls(what string, a, b []encCall, encEpoch map[string]bool) encCompared {
	out := encCompared{Shadow: map[string]int{}, NUL: map[string]int{}}
	bm := map[string][]Row{}
	for _, c := range b {
		bm[c.Name] = c.Rows
	}
	for _, c := range a {
		rb, ok := bm[c.Name]
		if !ok {
			out.Diffs = append(out.Diffs, fmt.Sprintf("%s: %s missing on the second arm", what, c.Name))
			continue
		}
		na, nb := encNormalize(c.Name, c.Rows), encNormalize(c.Name, rb)
		if encRowsText(na) != encRowsText(nb) {
			ca, _ := encF1NUL(c.Name, na)
			if cb, cut := encF1NUL(c.Name, nb); cut > 0 {
				out.NUL[c.Name] = cut
				na, nb = ca, cb
			}
		}
		na, n := encR18(c.Name, na, nb, encEpoch)
		out.R18 += n
		if extra, ok := encFastPathShadow(c.Name, na, nb); ok && extra > 0 {
			out.Shadow[c.Name] = extra
			continue
		}
		out.Diffs = append(out.Diffs, diffRows(what+": "+c.Name, na, nb)...)
	}
	return out
}

// encRowsText is rows as one comparable string.
func encRowsText(rows []Row) string {
	var b strings.Builder
	for _, r := range rows {
		b.WriteString(strictText(r))
		b.WriteByte('\n')
	}
	return b.String()
}

// encEpochDigests are the epoch-stream row digests of the records whose
// EPOCH the client encrypted (R18's rows).
func encEpochDigests(classes []encClass) map[string]bool {
	out := map[string]bool{}
	for _, c := range classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				if w.Type == "OMM.fbs" && f.Name == "EPOCH" {
					out[digestRow(frameRow(w.Bytes)).Get("h")] = true
				}
			}
		}
	}
	return out
}

func encWriteJSON(path string, v any) error {
	b, err := json.MarshalIndent(v, "", " ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

