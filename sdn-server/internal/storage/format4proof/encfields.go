// sentinel is a recognizable, single-token (FTS5 unicode61) plaintext.
func sentinel(tag string, i int) []byte {
	const alnum = "abcdefghijklmnopqrstuvwxyz0123456789"
	r := rnd(12)
	out := []byte(fmt.Sprintf("ZQ%s%02dx", tag, i))
	for _, b := range r {
		out = append(out, alnum[int(b)%len(alnum)])
	}
	return out
}

func buildKMFRec(keys encKeys, i int) (*encRec, error) {
	plain := append(sentinel("KMFKEY", i), rnd(8)...) // 32 bytes
	b := flatbuffers.NewBuilder(256)
	keyID := b.CreateString(fmt.Sprintf("enc-kmf-%02d", i))
	kb := b.CreateByteVector(plain)
	KMFfb.KMFStart(b)
	KMFfb.KMFAddKEY_ID(b, keyID)
	KMFfb.KMFAddROLE(b, 4)      // DecryptKey
	KMFfb.KMFAddALGORITHM(b, 5) // Aes256Gcm
	KMFfb.KMFAddENCODING(b, 1)  // RawBytes
	KMFfb.KMFAddKEY_BYTES(b, kb)
	KMFfb.KMFAddVERSION(b, uint32(100+i))
	KMFfb.KMFAddEXPIRES_AT(b, 1893456000000)
	KMFfb.FinishKMFBuffer(b, KMFfb.KMFEnd(b))
	buf := append([]byte(nil), b.FinishedBytes()...)
	rec := &encRec{Type: "KMF.fbs", Class: "kmf-vector", RecIdx: uint32(1000 + i), Program: fb3ProgramKMF, KeyName: "kmf"}
	if err := fb3Crypt(buf, keys.KMFKey, rec.RecIdx, fb3ProgramKMF); err != nil {
		return nil, err
	}
	ct := append([]byte(nil), KMFfb.GetRootAsKMF(buf, 0).KEY_BYTESBytes()...)
	if bytes.Equal(ct, plain) {
		return nil, errors.New("KMF: KEY_BYTES unchanged by encryption")
	}
	rec.Bytes, rec.CID = buf, storage.ComputeCID(buf)
	rec.Fields = []encField{{Name: "KEY_BYTES", Kind: "vector", Plain: plain, Cipher: ct}}
	return rec, nil
}

// lgrENC is an ecies header as LGR's nested $ENC table.
func lgrENC(b *flatbuffers.Builder, h ecies.Header, rootType string) flatbuffers.UOffsetT {
	eph := b.CreateByteVector(h.EphemeralPub)
	nonce := b.CreateByteVector(h.NonceStart)
	var rid flatbuffers.UOffsetT
	if len(h.RecipientKeyID) > 0 {
		rid = b.CreateByteVector(h.RecipientKeyID)
	}
	ctx := b.CreateString(h.Context)
	var rt flatbuffers.UOffsetT
	if rootType != "" {
		rt = b.CreateString(rootType)
	}
	LGRfb.ENCStart(b)
	LGRfb.ENCAddVERSION(b, 1)
	LGRfb.ENCAddKEY_EXCHANGE(b, LGRfb.KeyExchange(h.KeyExchange))
	LGRfb.ENCAddEPHEMERAL_PUBLIC_KEY(b, eph)
	LGRfb.ENCAddNONCE_START(b, nonce)
	if rid != 0 {
		LGRfb.ENCAddRECIPIENT_KEY_ID(b, rid)
	}
	LGRfb.ENCAddCONTEXT(b, ctx)
	if rt != 0 {
		LGRfb.ENCAddROOT_TYPE(b, rt)
	}
	return LGRfb.ENCEnd(b)
}

const (
	lgrPayloadFieldID = 17 // LGR.WRAPPED_CONTENT_KEY_PAYLOAD
	lgrSealContext    = "enc-proof/lgr-payload/v1"
)

func buildLGR(i int, class string, header func(b *flatbuffers.Builder) flatbuffers.UOffsetT, payload []byte) []byte {
	b := flatbuffers.NewBuilder(1024)
	req := b.CreateString(fmt.Sprintf("enc-lgr-%s-%02d", class, i))
	mod := b.CreateString("encproofmodule")
	status := b.CreateString("granted")
	dom := b.CreateString("enc-proof.invalid")
	pl := b.CreateByteVector(payload)
	hdr := header(b)
	LGRfb.LGRStart(b)
	LGRfb.LGRAddMESSAGE_TYPE(b, 1) // Granted
	LGRfb.LGRAddREQUEST_ID(b, req)
	LGRfb.LGRAddMODULE_ID(b, mod)
	LGRfb.LGRAddGRANTED_DOMAIN(b, dom)
	LGRfb.LGRAddGRANTED_TIMEOUT_MS(b, 3600000)
	LGRfb.LGRAddEXPIRES_AT(b, 1893456000000)
	LGRfb.LGRAddGRANT_STATUS(b, status)
	LGRfb.LGRAddWRAPPED_CONTENT_KEY_HEADER(b, hdr)
	LGRfb.LGRAddWRAPPED_CONTENT_KEY_PAYLOAD(b, pl)
	LGRfb.FinishLGRBuffer(b, LGRfb.LGREnd(b))
	return append([]byte(nil), b.FinishedBytes()...)
}

// buildLGRSealField: the payload is an ecies.SealField field (field id 17)
// with its header in the record's $ENC table.
func buildLGRSealField(keys encKeys, i int) (*encRec, error) {
	plain := append(sentinel("LGRSEAL", i), rnd(16)...)
	h, ct, err := ecies.SealField(keys.RecipPub, plain, lgrPayloadFieldID, ecies.WrapOptions{KeyExchange: ecies.X25519, Context: lgrSealContext,
		RecipientKeyID: []byte("enc-proof-recipient")})
	if err != nil {
		return nil, err
	}
	buf := buildLGR(i, "sealfield", func(b *flatbuffers.Builder) flatbuffers.UOffsetT { return lgrENC(b, h, "") }, ct)
	return &encRec{Type: "LGR.fbs", Class: "lgr-sealfield", Bytes: buf, CID: storage.ComputeCID(buf), KeyName: "recipient",
		Fields: []encField{{Name: "WRAPPED_CONTENT_KEY_PAYLOAD", Kind: "ecies", Plain: plain, Cipher: ct, FieldID: lgrPayloadFieldID, Context: lgrSealContext}}}, nil
}

// buildLGRWrap: the grant shape (ecies.Wrap): $ENC header naming ROOT_TYPE
// KMF, the payload a KMF whose KEY_BYTES carries the wrapped content key.
func buildLGRWrap(keys encKeys, i int) (*encRec, error) {
	contentKey := append(sentinel("LGRWRAP", i), rnd(12)...)[:32]
	encBytes, kmfBytes, err := ecies.Wrap(keys.RecipPub, contentKey, ecies.WrapOptions{KeyExchange: ecies.X25519, Context: ecies.DefaultGrantContext})
	if err != nil {
		return nil, err
	}
	_ = encBytes
	// Re-read the standalone $ENC into a Header for the nested table.
	hdr, err := headerOfENC(encBytes)
	if err != nil {
		return nil, err
	}
	buf := buildLGR(i, "wrap", func(b *flatbuffers.Builder) flatbuffers.UOffsetT { return lgrENC(b, hdr, "KMF") }, kmfBytes)
	wrapped := append([]byte(nil), KMFfb.GetRootAsKMF(kmfBytes, 0).KEY_BYTESBytes()...)
	return &encRec{Type: "LGR.fbs", Class: "lgr-wrap", Bytes: buf, CID: storage.ComputeCID(buf), KeyName: "recipient",
		Fields: []encField{{Name: "WRAPPED_CONTENT_KEY_PAYLOAD.KMF.KEY_BYTES", Kind: "ecies", Plain: contentKey, Cipher: wrapped, FieldID: 4, Context: ecies.DefaultGrantContext}}}, nil
}

func headerOfENC(encBytes []byte) (ecies.Header, error) {
	if len(encBytes) < 8 || string(encBytes[4:8]) != "$ENC" {
		return ecies.Header{}, errors.New("not an $ENC buffer")
	}
	t := flatbuffers.Table{Bytes: encBytes, Pos: flatbuffers.GetUOffsetT(encBytes)}
	vec := func(slot flatbuffers.VOffsetT) []byte {
		if o := flatbuffers.UOffsetT(t.Offset(slot)); o != 0 {
			return append([]byte(nil), t.ByteVector(o+t.Pos)...)
		}
		return nil
	}
	var kx ecies.KeyExchange
	if o := flatbuffers.UOffsetT(t.Offset(6)); o != 0 {
		kx = ecies.KeyExchange(t.GetInt8(o + t.Pos))
	}
	return ecies.Header{KeyExchange: kx, EphemeralPub: vec(12), NonceStart: vec(14), RecipientKeyID: vec(16), Context: string(vec(18))}, nil
}

