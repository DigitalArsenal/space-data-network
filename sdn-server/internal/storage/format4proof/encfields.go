// Encrypted fields (owner, 2026-10-04: "make sure that encrypted fields work as
// well"; contract C-46, ENCRYPTED-FIELDS.md): records whose fields a client
// encrypted, stored through SDN on fresh format-1 and format-4 stores with the
// same writes and read back through every surface, the engine treating them as
// the opaque FlatBuffers they are. DriveEncryptedFields beside DriveFeedNames:
//
//   - the records: KMF whose KEY_BYTES the client encrypted with the
//     flatbuffers field-encryption API (format 3, the generated KMF walk
//     program); LGR grants whose content-key payload is an ecies.SealField
//     field with its $ENC header, and the ecies.Wrap shape ($ENC naming
//     ROOT_TYPE KMF, a KMF payload); OMM and MPE whose scalar (NORAD_CAT_ID,
//     MEAN_MOTION) or string (OBJECT_ID, OBJECT_NAME, EPOCH, ENTITY_ID)
//     fields the client encrypted (a client schema variant marking them
//     (encrypted)): fields the index rules and full text read. Even records
//     go tagged (one StoreBatchWithSourceTags per class, its own feed), odd
//     ones untagged (one Store each, local). SDN also seals every KMF record
//     at rest (C-25: an SDF1 envelope to the store's key; whole-record
//     sealing itself is SDN's suite: storage's
//     TestFormat4SealedRecordsMatchFormat1);
//   - every read surface on format 4 equals format 1 field by field, outside
//     the named rulings (encRulings: C-9, C-41 N3, C-39 E7, R18, C-48 (a),
//     (b)); every record a read returns is the
//     written bytes and decrypts with the throwaway keys to the plaintext;
//   - on disk: format 4's streams walk to EOF as [u32 size][record] frames
//     holding the client's ciphertext; no plaintext (raw, hex, base64, the
//     scalars as text) in any file of either store, open or closed; the
//     stock-reader check (enc-reader-check.py: stock flatbuffers, the SDS
//     Python readers and the generated decryption, no FlatSQL or SDN code)
//     parses and decrypts every frame of the format-4 and migrated stores;
//   - store-migrate --to 4 of the format-1 store answers as format 1 does;
//   - the full-text regression of records aligned to a size prefix SDN cut
//     off (C-46 (3), I1): OMM records cut out of SDN's size-prefixed builder
//     beside the same records finished bare; format 4 finds them as format 1
//     does (the 3.7.0 engine found none of the cut ones).
//
// Every key is a throwaway made here (crypto/rand). The stores'
// field-encryption identity is pre-provisioned with a throwaway X25519 pair,
// so the sealed frames open with a key this driver made. SDN pins SDS lib/go
// 1.228.0, whose KMF package predates the format-3 API, so the generated
// walker (lib/go 1.232) is carried below verbatim; the Python check decrypts
// with the generated Python API, an independent implementation.

