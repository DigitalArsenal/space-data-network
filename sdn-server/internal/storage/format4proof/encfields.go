// encClasses builds the main scenario's classes (n records each; even
// records are delivered tagged, in one StoreBatchWithSourceTags per class,
// odd ones untagged, one Store each).
func encClasses(keys encKeys) ([]encClass, error) {
	type maker struct {
		name, typ string
		n         int
		fn        func(encKeys, int) (*encRec, error)
	}
	makers := []maker{
		{"kmf-vector", "KMF.fbs", 6, buildKMFRec},
		{"lgr-sealfield", "LGR.fbs", 4, buildLGRSealField},
		{"lgr-wrap", "LGR.fbs", 4, buildLGRWrap},
		{"omm-scalar", "OMM.fbs", 4, buildOMMScalar},
		{"omm-string", "OMM.fbs", 4, buildOMMString},
		{"omm-epoch", "OMM.fbs", 2, buildOMMEpoch},
		{"mpe-string", "MPE.fbs", 4, buildMPEString},
	}
	var out []encClass
	for _, m := range makers {
		c := encClass{Name: m.name, Type: m.typ}
		for i := 0; i < m.n; i++ {
			r, err := m.fn(keys, i)
			if err != nil {
				return nil, fmt.Errorf("%s %d: %w", m.name, i, err)
			}
			r.Tagged = i%2 == 0
			c.Recs = append(c.Recs, r)
		}
		out = append(out, c)
	}
	return out, nil
}

// ---- decrypt checks (the throwaway keys) -----------------------------------

// decryptCheck opens rec's encrypted fields in data (the bytes a read
// returned) with the throwaway keys and compares them with the plaintexts.
func decryptCheck(keys encKeys, rec *encRec, data []byte) string {
	if !bytes.Equal(data, rec.Bytes) {
		return "bytes differ from the written record"
	}
	buf := append([]byte(nil), data...)
	switch rec.KeyName {
	case "kmf", "field":
		key := keys.KMFKey
		if rec.KeyName == "field" {
			key = keys.FieldKey
		}
		if err := fb3Crypt(buf, key, rec.RecIdx, rec.Program); err != nil {
			return "decrypt: " + err.Error()
		}
		for _, f := range rec.Fields {
			var got []byte
			switch rec.Type + "." + f.Name {
			case "KMF.fbs.KEY_BYTES":
				got = KMFfb.GetRootAsKMF(buf, 0).KEY_BYTESBytes()
			case "OMM.fbs.NORAD_CAT_ID":
				got = u32le(OMMfb.GetRootAsOMM(buf, 0).NORAD_CAT_ID())
			case "OMM.fbs.MEAN_MOTION":
				got = f64le(OMMfb.GetRootAsOMM(buf, 0).MEAN_MOTION())
			case "OMM.fbs.OBJECT_ID":
				got = OMMfb.GetRootAsOMM(buf, 0).OBJECT_ID()
			case "OMM.fbs.OBJECT_NAME":
				got = OMMfb.GetRootAsOMM(buf, 0).OBJECT_NAME()
			case "OMM.fbs.EPOCH":
				got = OMMfb.GetRootAsOMM(buf, 0).EPOCH()
			case "MPE.fbs.ENTITY_ID":
				got = MPEfb.GetRootAsMPE(buf, 0).ENTITY_ID()
			case "MPE.fbs.EPOCH":
				got = f64le(MPEfb.GetRootAsMPE(buf, 0).EPOCH())
			default:
				return "no accessor for " + f.Name
			}
			if !bytes.Equal(got, f.Plain) {
				return fmt.Sprintf("%s decrypts to %x, want %x", f.Name, got, f.Plain)
			}
		}
		return "ok"
	case "recipient":
		l := LGRfb.GetRootAsLGR(buf, 0)
		e := l.WRAPPED_CONTENT_KEY_HEADER(nil)
		if e == nil {
			return "no $ENC header"
		}
		h := ecies.Header{KeyExchange: ecies.KeyExchange(e.KEY_EXCHANGE()), EphemeralPub: e.EPHEMERAL_PUBLIC_KEYBytes(), NonceStart: e.NONCE_STARTBytes(),
			RecipientKeyID: e.RECIPIENT_KEY_IDBytes(), Context: string(e.CONTEXT())}
		payload := l.WrappedContentKeyPayloadBytes()
		f := rec.Fields[0]
		ct := payload
		if rec.Class == "lgr-wrap" {
			if string(e.ROOT_TYPE()) != "KMF" || !KMFfb.KMFBufferHasIdentifier(payload) {
				return "wrap payload is not a KMF named by ROOT_TYPE"
			}
			ct = KMFfb.GetRootAsKMF(payload, 0).KEY_BYTESBytes()
		}
		got, err := ecies.OpenField(keys.RecipPriv, h, ct, f.FieldID, f.Context)
		if err != nil {
			return "open: " + err.Error()
		}
		if !bytes.Equal(got, f.Plain) {
			return fmt.Sprintf("payload opens to %x, want %x", got, f.Plain)
		}
		return "ok"
	case "none":
		return "ok"
	}
	return "no key for " + rec.KeyName
}

// ---- reads -----------------------------------------------------------------

type encCall struct {
	Name string `json:"name"`
	Rows []Row  `json:"rows"`
}

// encScen canonicalizes the store clock: a time at or after t0 reads
// "now@j", j the last write that began at or before it (every write begins in
// a later second than the previous one ended in).
type encScen struct {
	t0     int64
	writes []int64
	last   int64
}

func (sc *encScen) next() {
	for time.Now().Unix() <= sc.last {
		time.Sleep(20 * time.Millisecond)
	}
	sc.writes = append(sc.writes, time.Now().Unix())
}

func (sc *encScen) done() { sc.last = time.Now().Unix() }

func (sc *encScen) canon(row Row) Row {
	out := make(Row, len(row))
	for i, f := range row {
		v := f.V
		n := strings.ToLower(f.N)
		switch {
		case strings.Contains(n, "rowid"):
			if x, err := strconv.ParseInt(strings.Trim(v, `"`), 10, 64); err == nil && x > 0 {
				v = "new"
			}
		case timeField(n):
			if x, ok := unixValue(v); ok && x >= sc.t0 {
				j := -1
				for k, w := range sc.writes {
					if w <= x {
						j = k
					}
				}
				v = "now@" + strconv.Itoa(j)
			}
		}
		out[i] = Field{f.N, v}
	}
	return out
}

// encErrRow is an error as a row: its kind (compared) and its text
// ("~err_text", logged, never compared: the formats word errors apart).
func encErrRow(err error) Row { return Row{{"err", errKind(err)}, {"~err_text", err.Error()}} }

// recRow is a record row: RecordRow canonicalized, with sealed stored bytes
// read as "sealed" (their envelope is random per store) and, for a record
// this driver wrote, whether the bytes equal the written ones.
func (e *encRun) recRow(r *storage.Record) Row {
	row := e.sc.canon(RecordRow(r))
	if r == nil {
		return row
	}
	same := "n/a"
	if w := e.byCID[r.CID]; w != nil {
		same = strconv.FormatBool(bytes.Equal(r.Data, w.Bytes))
		if !bytes.Equal(r.Data, w.Bytes) && encfield.IsSealed(r.Data) {
			same = "sealed"
		}
	}
	for i := range row {
		if row[i].N == "data" && encfield.IsSealed(r.Data) {
			row[i].V = "sealed"
		}
	}
	return append(row, Field{"same_bytes", same})
}

// encRun is one scenario's reads on one arm (or its disk checks).
type encRun struct {
	logf    Logf
	keys    encKeys
	classes []encClass
	byCID   map[string]*encRec
	sc      *encScen
	out     string
	arm     string
	probs   *[]string
	only    []string // the types a scenario reads (default: the main scenario's four)
}

func (e *encRun) fail(f string, a ...any) {
	msg := fmt.Sprintf("%s: ", e.arm) + fmt.Sprintf(f, a...)
	*e.probs = append(*e.probs, msg)
	if e.logf != nil {
		e.logf("encfields: PROBLEM %s", msg)
	}
}

func (e *encRun) types() []string {
	if len(e.only) > 0 {
		return e.only
	}
	return []string{"KMF.fbs", "LGR.fbs", "OMM.fbs", "MPE.fbs"}
}

func (e *encRun) recsOf(typ string) []*encRec {
	var out []*encRec
	for _, c := range e.classes {
		if c.Type == typ {
			out = append(out, c.Recs...)
		}
	}
	return out
}

func (e *encRun) classesOf(typ string) []encClass {
	var out []encClass
	for _, c := range e.classes {
		if c.Type == typ {
			out = append(out, c)
		}
	}
	return out
}

// write applies the scenario's writes: per class, its tagged records in one
// StoreBatchWithSourceTags, then its untagged ones one Store each.
func (e *encRun) write(s *storage.FlatSQLStore) {
	for _, c := range e.classes {
		var tagged, untagged []*encRec
		for _, r := range c.Recs {
			if r.Tagged {
				tagged = append(tagged, r)
			} else {
				untagged = append(untagged, r)
			}
		}
		if len(tagged) > 0 {
			recs := make([][]byte, len(tagged))
			for i, r := range tagged {
				recs[i] = r.Bytes
			}
			e.sc.next()
			n, err := s.StoreBatchWithSourceTags(c.Type, recs, encPeer, encSig, storage.SourceTags{ProviderID: encProvider, SourceName: c.source(), BatchID: c.batch()})
			e.sc.done()
			if err != nil || n != len(recs) {
				e.fail("write %s tagged: stored %d of %d: %v", c.Name, n, len(recs), err)
			}
		}
		for _, r := range untagged {
			e.sc.next()
			id, err := s.Store(c.Type, r.Bytes, encPeer, encSig)
			e.sc.done()
			if err != nil || id != r.CID {
				e.fail("write %s untagged: cid %q (want %s): %v", c.Name, id, r.CID, err)
			}
		}
	}
}

func digestRows(bs [][]byte) []Row {
	rows := make([]Row, 0, len(bs))
	for _, b := range bs {
		k := "plain"
		if encfield.IsSealed(b) {
			k = "sealed"
		}
		rows = append(rows, ValueRow("len", strconv.Itoa(len(b)), "frame", digestOrSealed(b), "kind", k))
	}
	return sortRows(rows)
}

func digestOrSealed(b []byte) string {
	if encfield.IsSealed(b) {
		return "sealed"
	}
	return digest(b)
}

// answers reads everything the scenario wrote, through every surface that
// applies, as canonical rows.
func (e *encRun) answers(s *storage.FlatSQLStore, label string) []encCall {
	var calls []encCall
	add := func(name string, rows []Row) { calls = append(calls, encCall{Name: name, Rows: rows}) }
	recs := func(name string, list []*storage.Record, err error) {
		if err != nil {
			add(name, []Row{encErrRow(err)})
			return
		}
		rows := make([]Row, 0, len(list))
		for _, r := range list {
			rows = append(rows, e.recRow(r))
			if w := e.byCID[r.CID]; w != nil && !encfield.IsSealed(r.Data) && !bytes.Equal(r.Data, w.Bytes) {
				e.fail("%s %s: %s returns other bytes than written", label, name, r.CID)
			}
		}
		add(name, rows)
	}
	for _, typ := range e.types() {
		// GET by CID: bytes and the throwaway-key decrypt.
		var rows []Row
		for _, w := range e.recsOf(typ) {
			r, err := s.GetRecord(typ, w.CID)
			if err != nil {
				rows = append(rows, append(Row{{"cid", w.CID}}, encErrRow(err)...))
				e.fail("%s GET %s %s: %v", label, typ, w.CID, err)
				continue
			}
			dec := decryptCheck(e.keys, w, r.Data)
			if dec != "ok" {
				e.fail("%s GET %s %s: %s", label, typ, w.CID, dec)
			}
			rows = append(rows, e.sc.canon(append(getRow(r), Field{"same_bytes", strconv.FormatBool(bytes.Equal(r.Data, w.Bytes))}, Field{"decrypt", dec})))
		}
		add("GET "+typ, rows)
		// TAGS.
		rows = nil
		for _, w := range e.recsOf(typ) {
			tg, err := s.GetSourceTags(typ, w.CID)
			if err != nil {
				rows = append(rows, append(Row{{"cid", w.CID}}, encErrRow(err)...))
				continue
			}
			rows = append(rows, TagsRow(w.CID, tg))
		}
		add("TAGS "+typ, rows)
		// SCAN / data pages.
		l, err := s.QueryRawRecords(storage.RawRecordQuery{SchemaName: typ, UseRowIDCursor: true, Limit: 1000})
		recs("SCAN cursor "+typ, l, err)
		l, err = s.QueryRawRecords(storage.RawRecordQuery{SchemaName: typ, Limit: 1000})
		recs("SCAN newest "+typ, l, err)
		l, err = s.QueryRawRecordRefs(storage.RawRecordQuery{SchemaName: typ, UseRowIDCursor: true, Limit: 1000})
		recs("SCAN refs (stored bytes) "+typ, l, err)
		// The sealed stored bytes open with the store's throwaway key to the written record.
		if err == nil {
			for _, r := range l {
				if !encfield.IsSealed(r.Data) {
					continue
				}
				w := e.byCID[r.CID]
				opened, was, oerr := encfield.Open(strings.TrimSuffix(typ, ".fbs"), r.Data, e.keys.StorePriv, storeFieldEncryptionContext)
				switch {
				case oerr != nil || !was:
					e.fail("%s refs %s %s: the sealed bytes do not open with the store key: %v", label, typ, r.CID, oerr)
				case w == nil || !bytes.Equal(opened, w.Bytes):
					e.fail("%s refs %s %s: the sealed bytes open to other bytes than written", label, typ, r.CID)
				}
			}
		}
		for _, c := range e.classesOf(typ) {
			l, err = s.QuerySourceTaggedRecords(storage.SourceTagQuery{SchemaName: typ, ProviderID: encProvider, SourceName: c.source(), Limit: 1000})
			recs("LANE "+typ+" "+c.source(), l, err)
			n, err := s.CountRawRecords(storage.RawRecordQuery{SchemaName: typ, ProviderID: encProvider, SourceName: c.source()})
			if err != nil {
				add("COUNT lane "+typ+" "+c.source(), []Row{encErrRow(err)})
			} else {
				add("COUNT lane "+typ+" "+c.source(), []Row{ValueRow("lane_n", i64(n))})
			}
		}
		l, err = s.QueryRecentRecords(typ, 1000)
		recs("RECENT "+typ, l, err)
		p, err := s.FullTablePageWithCursor(storage.FullTablePageQuery{SchemaName: typ, Limit: 1000})
		recs("TABLE PAGE "+typ, p.Records, err)
		all, err := s.QueryAllBounded(typ, 1000, 64<<20)
		if err != nil {
			add("ALL BOUNDED "+typ, []Row{encErrRow(err)})
		} else {
			add("ALL BOUNDED "+typ, digestRows(all))
		}
		n, err := s.Count(typ)
		if err != nil {
			add("COUNT "+typ, []Row{encErrRow(err)})
		} else {
			add("COUNT "+typ, []Row{ValueRow("n", i64(n))})
		}
		q := storage.RawRecordQuery{SchemaName: typ}
		cnt, h, err := s.RawRecordSnapshot(q)
		if err != nil {
			add("HEAD "+typ, []Row{encErrRow(err)})
		} else {
			add("HEAD "+typ, []Row{e.sc.canon(covHead(q, cnt, &h))})
		}
		l, err = s.QueryIndexedRecords(storage.IndexedRecordQuery{SchemaName: typ, Limit: 1000, AllowLargeResultSet: true})
		recs("INDEXED "+typ, l, err)
		ip, total, err := s.RecordIndexPage(storage.RecordIndexPageQuery{SchemaName: typ, Limit: 1000})
		if err != nil {
			add("INDEX PAGE "+typ, []Row{encErrRow(err)})
		} else {
			rows = []Row{ValueRow("total", i64(total))}
			for _, r := range ip {
				rows = append(rows, ValueRow("cid", r.CID, "norad", i64p(r.NoradCatID), "epoch", i64p(r.EpochUnix)))
			}
			add("INDEX PAGE "+typ, rows)
		}
	}
	// Indexed reads that filter on an encrypted field (OMM's NORAD and
	// OBJECT_ID, MPE's ENTITY_ID): the plaintext finds nothing, the
	// ciphertext (what the record holds) finds its record.
	for _, c := range e.classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				var qs []storage.IndexedRecordQuery
				var names []string
				switch c.Type + "." + f.Name {
				case "OMM.fbs.NORAD_CAT_ID":
					pv, cv := binary.LittleEndian.Uint32(f.Plain), binary.LittleEndian.Uint32(f.Cipher)
					qs = append(qs, storage.IndexedRecordQuery{SchemaName: c.Type, NoradCatID: u32(pv), Limit: 100},
						storage.IndexedRecordQuery{SchemaName: c.Type, NoradCatID: u32(cv), Limit: 100})
					names = append(names, "plaintext", "ciphertext")
				case "OMM.fbs.OBJECT_ID", "MPE.fbs.ENTITY_ID":
					qs = append(qs, storage.IndexedRecordQuery{SchemaName: c.Type, EntityID: string(f.Plain), Limit: 100},
						storage.IndexedRecordQuery{SchemaName: c.Type, EntityID: string(f.Cipher), Limit: 100})
					names = append(names, "plaintext", "ciphertext")
				}
				for k, iq := range qs {
					l, err := s.QueryIndexedRecords(iq)
					recs(fmt.Sprintf("INDEXED %s %s=%s of %s", c.Type, f.Name, names[k], w.CID), l, err)
				}
			}
		}
	}
	calls = append(calls, e.epochAnswers(s)...)
	calls = append(calls, e.sqlAnswers(s)...)
	calls = append(calls, e.exportAnswers(s, label)...)
	calls = append(calls, e.ftsAnswers(s)...)
	for _, fn := range []string{"DataSummary", "SourceBatchProgress", "ProducerSourceProgress", "SourceRecordCounts", "SchemaDateRanges", "LiveRecordBytes"} {
		v, err := summaryFetch(s, fn, "")
		if err != nil {
			add("SUMMARY "+fn, []Row{encErrRow(err)})
			continue
		}
		rows, err := summaryRows(v)
		if err != nil {
			add("SUMMARY "+fn, []Row{encErrRow(err)})
			continue
		}
		for i := range rows {
			rows[i] = e.sc.canon(rows[i])
		}
		add("SUMMARY "+fn, sortRows(rows))
	}
	return calls
}

func (e *encRun) epochAnswers(s *storage.FlatSQLStore) []encCall {
	var calls []encCall
	add := func(name string, rows []Row) { calls = append(calls, encCall{Name: name, Rows: rows}) }
	at := time.Unix(encEpoch0+30*60+30, 0).UTC()
	from, to := time.Unix(encEpoch0-3600, 0).UTC(), time.Unix(encEpoch0+7200, 0).UTC()
	var qs []storage.EpochRecordQuery
	for _, typ := range []string{"OMM.fbs", "MPE.fbs"} {
		for _, prof := range []string{storage.EpochProfileNearest, storage.EpochProfileAsOf, storage.EpochProfileForward} {
			qs = append(qs, storage.EpochRecordQuery{SchemaName: typ, Profile: prof, At: at, Limit: 100},
				storage.EpochRecordQuery{SchemaName: typ, Profile: prof, At: at, Limit: 100, IncludeSource: true})
			for _, c := range e.classesOf(typ) {
				qs = append(qs, storage.EpochRecordQuery{SchemaName: typ, Profile: prof, At: at, ProviderID: encProvider, SourceName: c.source(), Limit: 100})
			}
		}
		qs = append(qs, storage.EpochRecordQuery{SchemaName: typ, Profile: storage.EpochProfileDay, Day: "2026-09-20", Limit: 100},
			storage.EpochRecordQuery{SchemaName: typ, Profile: storage.EpochProfileWindow, From: &from, To: &to, Limit: 100},
			storage.EpochRecordQuery{SchemaName: typ, Profile: storage.EpochProfileCoverage})
	}
	// Entity filters on encrypted fields: plaintext and ciphertext.
	for _, c := range e.classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				switch c.Type + "." + f.Name {
				case "OMM.fbs.NORAD_CAT_ID":
					qs = append(qs, storage.EpochRecordQuery{SchemaName: c.Type, Profile: storage.EpochProfileNearest, At: at, NoradCatID: u32(binary.LittleEndian.Uint32(f.Plain)), Limit: 10},
						storage.EpochRecordQuery{SchemaName: c.Type, Profile: storage.EpochProfileNearest, At: at, NoradCatID: u32(binary.LittleEndian.Uint32(f.Cipher)), Limit: 10})
				case "MPE.fbs.ENTITY_ID":
					qs = append(qs, storage.EpochRecordQuery{SchemaName: c.Type, Profile: storage.EpochProfileAsOf, At: at, EntityID: string(f.Plain), Limit: 10},
						storage.EpochRecordQuery{SchemaName: c.Type, Profile: storage.EpochProfileAsOf, At: at, EntityID: string(f.Cipher), Limit: 10})
				}
			}
		}
	}
	for _, p := range qs {
		name := fmt.Sprintf("EPOCH %s %s at=%d", p.SchemaName, p.Profile, p.At.Unix())
		if p.SourceName != "" {
			name += " source=" + p.SourceName
		}
		if p.IncludeSource {
			name += " include_source"
		}
		if p.NoradCatID != nil {
			name += fmt.Sprintf(" norad=%d", *p.NoradCatID)
		}
		if p.EntityID != "" {
			name += " entity=" + hex.EncodeToString([]byte(p.EntityID))
		}
		if p.Day != "" {
			name += " day=" + p.Day
		}
		if p.Profile == storage.EpochProfileCoverage {
			bs, err := s.QueryEpochCoverage(p)
			if err != nil {
				add(name, []Row{encErrRow(err)})
				continue
			}
			var rows []Row
			for _, b := range bs {
				rows = append(rows, ValueRow("day", b.Day, "n", i64(b.Count), "oldest", unixOf(b.OldestEpoch), "newest", unixOf(b.NewestEpoch)))
			}
			add(name, rows)
			continue
		}
		n, err := s.CountEpochRecords(p)
		if err != nil {
			add(name, []Row{encErrRow(err)})
			continue
		}
		ms, err := s.QueryEpochRecords(p)
		if err != nil {
			add(name, []Row{encErrRow(err)})
			continue
		}
		a, _ := matchesAnswer(name, ms, n)
		rows := make([]Row, 0, len(a.Rows))
		for _, r := range a.Rows {
			c := e.sc.canon(r)
			// The entity key may hold ciphertext: compare its bytes as hex.
			for i := range c {
				if c[i].N == "entity" && !utf8.ValidString(c[i].V) {
					c[i].V = "hex:" + hex.EncodeToString([]byte(c[i].V))
				}
			}
			rows = append(rows, c)
		}
		add(name, rows)
		for _, m := range ms {
			if m.Record == nil {
				continue
			}
			if w := e.byCID[m.Record.CID]; w != nil && !bytes.Equal(m.Record.Data, w.Bytes) {
				e.fail("%s: %s returns other bytes than written", name, m.Record.CID)
			}
		}
	}
	// The epoch streams (the SQL surface's EPOCH relation).
	for _, typ := range []string{"OMM.fbs", "MPE.fbs"} {
		sources := []string{"local"}
		for _, c := range e.classesOf(typ) {
			sources = append(sources, c.source())
		}
		for _, src := range sources {
			for _, prof := range []string{"nearest", "as_of", "forward"} {
				name := fmt.Sprintf("EPOCH STREAM %s@%s %s", typ, src, prof)
				st, err := s.QueryEpochRawStream(typ, src, prof, float64(at.Unix())+0.5, 0)
				if err != nil {
					add(name, []Row{encErrRow(err)})
					continue
				}
				fr, err := FrameRows(st.Bytes)
				if err != nil {
					add(name, []Row{encErrRow(err)})
					continue
				}
				add(name, unorderedDigest(fr))
			}
		}
	}
	return calls
}

func (e *encRun) sqlAnswers(s *storage.FlatSQLStore) []encCall {
	var calls []encCall
	add := func(name string, rows []Row) { calls = append(calls, encCall{Name: name, Rows: rows}) }
	jsonSQL := func(stmt string) {
		payload, _, _, err := s.QuerySandboxedJSON(stmt, sandboxCaps)
		if err != nil {
			add("SQL "+stmt, []Row{encErrRow(err)})
			return
		}
		valid := utf8.Valid(payload)
		rows, err := JSONRows(payload)
		if err != nil {
			add("SQL "+stmt, []Row{encErrRow(err), {{"utf8", strconv.FormatBool(valid)}}})
			return
		}
		add("SQL "+stmt, append([]Row{{{"utf8", strconv.FormatBool(valid)}}}, sortRows(rows)...))
	}
	streamSQL := func(stmt string) {
		st, err := s.QuerySandboxedStream(stmt, sandboxCaps)
		if err != nil {
			add("SQL STREAM "+stmt, []Row{encErrRow(err)})
			return
		}
		fr, err := FrameRows(st.Bytes)
		if err != nil {
			add("SQL STREAM "+stmt, []Row{encErrRow(err)})
			return
		}
		add("SQL STREAM "+stmt, unorderedDigest(fr))
		// Every frame the SQL surface streams is a record this driver wrote,
		// byte for byte (a sealed one opens with the store key to it).
		b := st.Bytes
		for len(b) >= 4 {
			n := int(binary.LittleEndian.Uint32(b))
			if len(b) < 4+n {
				break
			}
			fr := b[4 : 4+n]
			b = b[4+n:]
			if n == 0 {
				continue
			}
			if encfield.IsSealed(fr) {
				e.fail("SQL STREAM %s: streams a sealed frame", stmt)
				continue
			}
			if w := e.byCID[storage.ComputeCID(fr)]; w == nil || !bytes.Equal(w.Bytes, fr) {
				e.fail("SQL STREAM %s: streams bytes this driver did not write (cid %s)", stmt, storage.ComputeCID(fr))
			}
		}
	}
	selSQL := func(prefix, stmt string) {
		r, err := s.SandboxedSelect(context.Background(), stmt, storage.SandboxSelectCaps{MaxRows: 1000, MaxBytes: 16 << 20, Timeout: time.Minute})
		if err != nil {
			add(prefix+stmt, []Row{encErrRow(err)})
			return
		}
		rows := []Row{{{"columns", strings.Join(r.Columns, ",")}, {"truncated", strconv.FormatBool(r.Truncated)}}}
		var body []Row
		for _, cells := range r.Rows {
			row := Row{}
			for i, v := range cells {
				if !utf8.ValidString(v) {
					v = "hex:" + hex.EncodeToString([]byte(v))
				}
				row = append(row, Field{r.Columns[i], v})
			}
			body = append(body, row)
		}
		add(prefix+stmt, append(rows, sortRows(body)...))
	}
	for _, typ := range e.types() {
		code := strings.TrimSuffix(typ, ".fbs")
		jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "%s"`, code))
		jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "%s@local"`, code))
		for _, c := range e.classesOf(typ) {
			jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "%s@%s"`, code, c.source()))
		}
		jsonSQL(fmt.Sprintf(`SELECT * FROM "%s"`, code))
		streamSQL(fmt.Sprintf(`SELECT _data FROM "%s"`, code))
		// SandboxedSelect's SELECT * (C-47: format 1's fast path renders
		// _source, _data, bool and uint32 its own way) on the type, in lower
		// case, and on each feed's relation and local (encFastPathShadow).
		selSQL("SELECT ", fmt.Sprintf(`SELECT * FROM "%s"`, code))
		selSQL("SELECT ", fmt.Sprintf(`select  *  from %s ;`, strings.ToLower(code)))
		selSQL("SELECT ", fmt.Sprintf(`SELECT * FROM "%s@local"`, code))
		for _, c := range e.classesOf(typ) {
			selSQL("SELECT ", fmt.Sprintf(`SELECT * FROM "%s@%s"`, code, c.source()))
		}
	}
	selSQL("SELECT ", `SELECT hex(OBJECT_ID) AS id, hex(OBJECT_NAME) AS name, MEAN_MOTION, hex(EPOCH) AS epoch FROM "OMM"`)
	selSQL("SELECT ", `SELECT NORAD_CAT_ID FROM "OMM"`)
	selSQL("SELECT ", `SELECT hex(ENTITY_ID) AS id, EPOCH FROM "MPE"`)
	selSQL("SELECT ", `SELECT REQUEST_ID, length(_data) AS n FROM "LGR"`)
	selSQL("SELECT ", `SELECT COUNT(*) AS n FROM "KMF"`)
	jsonSQL(`SELECT hex(OBJECT_ID) AS id, hex(OBJECT_NAME) AS name, NORAD_CAT_ID, MEAN_MOTION, hex(EPOCH) AS epoch FROM "OMM"`)
	jsonSQL(`SELECT OBJECT_ID, OBJECT_NAME, EPOCH FROM "OMM"`)
	jsonSQL(`SELECT hex(ENTITY_ID) AS id, EPOCH FROM "MPE"`)
	for _, c := range e.classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				if c.Type+"."+f.Name == "OMM.fbs.NORAD_CAT_ID" {
					jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "OMM" WHERE NORAD_CAT_ID = %d`, binary.LittleEndian.Uint32(f.Plain)))
					jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "OMM" WHERE NORAD_CAT_ID = %d`, binary.LittleEndian.Uint32(f.Cipher)))
					jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "OMM" WHERE NORAD_CAT_ID = %d`, int32(binary.LittleEndian.Uint32(f.Cipher))))
				}
				if c.Type+"."+f.Name == "OMM.fbs.OBJECT_ID" {
					jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "OMM" WHERE OBJECT_ID = '%s'`, string(f.Plain)))
					jsonSQL(fmt.Sprintf(`SELECT COUNT(*) AS n FROM "OMM" WHERE hex(OBJECT_ID) = '%X'`, f.Cipher))
				}
			}
		}
	}
	return calls
}

// exportAnswers: ExportDatasetWindow of each feed and of each type.
func (e *encRun) exportAnswers(s *storage.FlatSQLStore, label string) []encCall {
	var calls []encCall
	add := func(name string, rows []Row) { calls = append(calls, encCall{Name: name, Rows: rows}) }
	var qs []storage.IndexedRecordQuery
	for _, c := range e.classes {
		qs = append(qs, storage.IndexedRecordQuery{SchemaName: c.Type, ProviderID: encProvider, SourceName: c.source(), BatchID: c.batch(), Limit: 1000})
	}
	for _, typ := range e.types() {
		qs = append(qs, storage.IndexedRecordQuery{SchemaName: typ, Limit: 1000})
	}
	for i, q := range qs {
		name := fmt.Sprintf("EXPORT %s source=%s", q.SchemaName, q.SourceName)
		dir := filepath.Join(e.out, "exports", label, strconv.Itoa(i))
		_ = os.RemoveAll(dir)
		ex, err := s.ExportDatasetWindow(dir, q)
		if err != nil {
			add(name, []Row{encErrRow(err)})
			continue
		}
		rows := []Row{ValueRow("records", strconv.Itoa(ex.RecordCount), "query", ex.QuerySHA256, "result", ex.ResultSHA256, "shard", ex.ShardSHA256,
			"shard_cid", ex.ShardCID, "index", ex.IndexSHA256, "shard_bytes", i64(ex.ShardBytes))}
		raw, err := os.ReadFile(ex.IndexPath)
		if err != nil {
			add(name, append(rows, encErrRow(err)))
			continue
		}
		rows = append(rows, ValueRow("index_utf8", strconv.FormatBool(utf8.Valid(raw)), "index_json_valid", strconv.FormatBool(json.Valid(raw))))
		var idx storage.DatasetExportIndex
		if err := json.Unmarshal(raw, &idx); err != nil {
			add(name, append(rows, encErrRow(err)))
			continue
		}
		shard, err := os.ReadFile(ex.ShardPath)
		if err != nil {
			add(name, append(rows, encErrRow(err)))
			continue
		}
		for _, r := range idx.Records {
			// The shard is [u32 LE size][record] frames; Offset names the
			// size, Length the record (ExportDatasetRecords).
			var frame []byte
			if r.Offset >= 0 && r.Length >= 0 && r.Offset+4+r.Length <= int64(len(shard)) {
				frame = shard[r.Offset+4 : r.Offset+4+r.Length]
			}
			same := "n/a"
			if w := e.byCID[r.CID]; w != nil {
				same = strconv.FormatBool(bytes.Equal(frame, w.Bytes))
				if same != "true" {
					e.fail("%s %s: the shard holds other bytes than written for %s", label, name, r.CID)
				}
			}
			norad := ""
			if r.NoradCatID != nil {
				norad = strconv.FormatUint(uint64(*r.NoradCatID), 10)
			}
			rows = append(rows, ValueRow("cid", r.CID, "offset", i64(r.Offset), "length", i64(r.Length), "norad", norad,
				"entity_hex", hex.EncodeToString([]byte(r.EntityID)), "epoch", i64p(r.EpochUnix), "same_bytes", same,
				"provider", r.SourceTags.ProviderID, "source", r.SourceTags.SourceName, "batch", r.SourceTags.BatchID))
		}
		add(name, rows)
	}
	return calls
}

// ftsAnswers: full-text search on records with encrypted string fields.
// The plaintext of an encrypted field must find nothing; an unencrypted
// token finds its records.
func (e *encRun) ftsAnswers(s *storage.FlatSQLStore) []encCall {
	var calls []encCall
	add := func(name string, rows []Row) { calls = append(calls, encCall{Name: name, Rows: rows}) }
	_, _, werr := s.WarmFullTextIndexes()
	// Every type searched below, records or none: format 1 builds an index
	// on first demand and answers "building" until it is ready, an empty
	// type's too (C-46 (2): then no rows, as format 4 answers at once, its
	// state "cold"); a type with records waits for "ready" on both formats.
	searched := map[string]bool{"OMM.fbs": true, "LGR.fbs": true, "KMF.fbs": true}
	for _, typ := range e.types() {
		searched[typ] = true
	}
	for typ := range searched {
		// A type without full text (KMF: "unavailable" on both formats)
		// has no index to wait for.
		if err := s.CheckFullTextSearch(typ, "warm"); err != nil && !strings.Contains(strings.ToLower(err.Error()), "building") {
			delete(searched, typ)
		}
	}
	deadline := time.Now().Add(10 * time.Minute)
	for typ := range searched {
		empty := len(e.recsOf(typ)) == 0
		for time.Now().Before(deadline) {
			st := s.FullTextIndexState(typ)
			if st == "ready" || st == "failed" || st == "disabled" || st == "unsupported" || (empty && st == "cold") {
				break
			}
			time.Sleep(time.Second)
		}
	}
	rows := []Row{}
	if werr != nil {
		rows = append(rows, encErrRow(werr))
	}
	for _, typ := range e.types() {
		rows = append(rows, ValueRow("type", typ, "state", s.FullTextIndexState(typ)))
	}
	add("FTS states", rows)
	search := func(typ, q string) {
		name := fmt.Sprintf("FTS %s %q", typ, q)
		if err := s.CheckFullTextSearch(typ, q); err != nil {
			add(name+" check", []Row{encErrRow(err)})
		}
		l, err := s.QueryRawRecords(storage.RawRecordQuery{SchemaName: typ, Search: q, UseRowIDCursor: true, Limit: 100})
		if err != nil {
			add(name, []Row{encErrRow(err)})
			return
		}
		rows := make([]Row, 0, len(l))
		for _, r := range l {
			rows = append(rows, e.recRow(r))
		}
		add(name, rows)
	}
	// Full text follows the records in the background on both formats
	// ("ready" is the state of the last pass): wait until the positive
	// controls answer every record that carries the token (or a minute), and
	// report how long that took.
	settle := func(typ, q string, want int) {
		st := time.Now()
		got := 0
		for time.Since(st) < time.Minute {
			l, err := s.QueryRawRecords(storage.RawRecordQuery{SchemaName: typ, Search: q, UseRowIDCursor: true, Limit: 100})
			if err == nil {
				got = len(l)
			}
			if got >= want {
				break
			}
			_ = s.CheckFullTextSearch(typ, q)
			time.Sleep(500 * time.Millisecond)
		}
		add(fmt.Sprintf("FTS settle %s %q", typ, q), []Row{{{"want", strconv.Itoa(want)}, {"got", strconv.Itoa(got)}, {"~seconds", fmt.Sprintf("%.1f", time.Since(st).Seconds())}}})
	}
	nOMM := 0
	for _, c := range e.classesOf("OMM.fbs") {
		if c.Name == "omm-scalar" || c.Name == "omm-epoch" {
			nOMM += len(c.Recs)
		}
	}
	settle("OMM.fbs", "ENCPROOF", nOMM)
	settle("LGR.fbs", "encproofmodule", len(e.recsOf("LGR.fbs")))
	search("OMM.fbs", "ENCPROOF")
	search("LGR.fbs", "encproofmodule")
	search("KMF.fbs", "enc")
	for _, c := range e.classes {
		for _, w := range c.Recs {
			for _, f := range w.Fields {
				if f.Kind == "string" || (f.Kind == "ecies" && c.Type == "LGR.fbs") || (f.Kind == "vector") {
					tok := string(f.Plain)
					if f.Name == "EPOCH" {
						tok = "2026"
					}
					if i := bytes.IndexByte(f.Plain, 'x'); f.Kind != "string" && i > 0 {
						tok = string(f.Plain[:i+1+12])
					}
					search(c.Type, tok)
				}
			}
		}
	}
	return calls
}

