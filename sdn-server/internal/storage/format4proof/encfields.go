// ommPlain builds an OMM finished WITHOUT a size prefix (FinishOMMBuffer), so
// its 8-byte fields are aligned to the record's first byte, as the fixture's
// production OMM records are. (sds.NewOMMBuilder finishes size-prefixed; a
// record cut out of it has its doubles 4 bytes off, which format 4's full
// text refuses: TestEncProbeAlign.)
func ommPlain(name, objID string, norad uint32, mm float64, epoch string, epochTS float64) []byte {
	b := flatbuffers.NewBuilder(512)
	nm := b.CreateString(name)
	id := b.CreateString(objID)
	center := b.CreateString("EARTH")
	ep := b.CreateString(epoch)
	created := b.CreateString("2026-10-01T00:00:00Z")
	OMMfb.OMMStart(b)
	OMMfb.OMMAddCREATION_DATE(b, created)
	OMMfb.OMMAddOBJECT_NAME(b, nm)
	OMMfb.OMMAddOBJECT_ID(b, id)
	OMMfb.OMMAddCENTER_NAME(b, center)
	OMMfb.OMMAddEPOCH(b, ep)
	OMMfb.OMMAddMEAN_MOTION(b, mm)
	OMMfb.OMMAddECCENTRICITY(b, 0.0007)
	OMMfb.OMMAddINCLINATION(b, 51.6)
	OMMfb.OMMAddRA_OF_ASC_NODE(b, 120.5)
	OMMfb.OMMAddARG_OF_PERICENTER(b, 80.25)
	OMMfb.OMMAddMEAN_ANOMALY(b, 279.75)
	OMMfb.OMMAddNORAD_CAT_ID(b, norad)
	OMMfb.OMMAddBSTAR(b, 0.00012)
	OMMfb.OMMAddUSER_DEFINED_EPOCH_TIMESTAMP(b, epochTS)
	OMMfb.FinishOMMBuffer(b, OMMfb.OMMEnd(b))
	return append([]byte(nil), b.FinishedBytes()...)
}

// ommPlainPrefixed is the same record through SDN's size-prefixed builder,
// cut out of its prefix (crashRecords' shape): its doubles sit 4 bytes off.
func ommPlainPrefixed(name, objID string, norad uint32, mm float64, epoch string, epochTS float64) []byte {
	b := sds.NewOMMBuilder().
		WithNoradCatID(norad).
		WithObjectName(name).
		WithObjectID(objID).
		WithEpoch(epoch).
		WithEpochTimestamp(epochTS).
		WithMeanMotion(mm).
		WithEccentricity(0.0007).
		WithInclination(51.6).
		WithCreationDate("2026-10-01T00:00:00Z").
		Build()
	return append([]byte(nil), b[4:]...)
}

func epochTS(i int) float64 { return float64(encEpoch0 + int64(i)*60) }

func epochText(i int) string {
	return time.Unix(encEpoch0+int64(i)*60, 0).UTC().Format("2006-01-02T15:04:05.000000")
}

func u32le(v uint32) []byte { return binary.LittleEndian.AppendUint32(nil, v) }
func f64le(v float64) []byte {
	return binary.LittleEndian.AppendUint64(nil, math.Float64bits(v))
}

// buildOMMScalar: NORAD_CAT_ID (uint32) and MEAN_MOTION (double) encrypted;
// OBJECT_NAME stays plaintext ("ENCPROOF SCALAR i": the full-text control).
func buildOMMScalar(keys encKeys, i int) (*encRec, error) {
	norad := uint32(0x5EC20000 + i*7 + 1)
	mm := 15.48919103 + float64(i)/1024
	buf := ommPlain(fmt.Sprintf("ENCPROOF SCALAR %d", i), fmt.Sprintf("2026-%03dZ", 900+i), norad, mm, epochText(i), epochTS(i))
	rec := &encRec{Type: "OMM.fbs", Class: "omm-scalar", RecIdx: uint32(2000 + i), Program: fb3ProgramOMMScalar, KeyName: "field"}
	if err := fb3Crypt(buf, keys.FieldKey, rec.RecIdx, rec.Program); err != nil {
		return nil, err
	}
	o := OMMfb.GetRootAsOMM(buf, 0)
	rec.Bytes, rec.CID = buf, storage.ComputeCID(buf)
	rec.Fields = []encField{
		{Name: "NORAD_CAT_ID", Kind: "u32", Plain: u32le(norad), Cipher: u32le(o.NORAD_CAT_ID())},
		{Name: "MEAN_MOTION", Kind: "f64", Plain: f64le(mm), Cipher: f64le(o.MEAN_MOTION())},
	}
	return rec, nil
}

