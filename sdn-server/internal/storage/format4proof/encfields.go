// ---- field-encryption format 3 (the generated walker, SDS lib/go 1.232 KMF) --
//
// Copied from the fork's generated Go (spacedatastandards.org lib/go/KMF/
// flatbuffers_encryption.go, "Code generated by the FlatBuffers compiler"):
// SDN pins lib/go v1.228.0, whose KMF package still carries the retired
// encryption-context API. The KMF walk program is the generated one; the
// OMM/MPE programs are a client's schema variant (the same op codes: 0 a
// scalar of arg bytes, 1 a string).

type fb3Err string

func (e fb3Err) Error() string { return string(e) }

type fb3Walk struct {
	buf     []byte
	program []int
	block   cipher.Block
	tables  map[int64]bool
	regions map[int64]bool
}

func (w *fb3Walk) fail(what string) { panic(fb3Err("FlatbuffersEncryption: " + what)) }
func (w *fb3Walk) check(pos, length int64) {
	size := int64(len(w.buf))
	if pos < 0 || length < 0 || pos > size || length > size-pos {
		w.fail(fmt.Sprintf("the buffer is malformed (offset %d out of bounds)", pos))
	}
}
func (w *fb3Walk) u16(pos int64) int64 {
	w.check(pos, 2)
	return int64(binary.LittleEndian.Uint16(w.buf[pos:]))
}
func (w *fb3Walk) u32(pos int64) int64 {
	w.check(pos, 4)
	return int64(binary.LittleEndian.Uint32(w.buf[pos:]))
}
func (w *fb3Walk) i32(pos int64) int64 {
	w.check(pos, 4)
	return int64(int32(binary.LittleEndian.Uint32(w.buf[pos:])))
}
func (w *fb3Walk) follow(pos int64) int64 {
	target := pos + w.u32(pos)
	w.check(target, 4)
	return target
}
func (w *fb3Walk) count(pos, elementSize int64) int64 {
	n := w.u32(pos)
	w.check(pos+4, n*elementSize)
	return n
}
func (w *fb3Walk) crypt(start, length int64) {
	if length == 0 || w.regions[start] {
		return
	}
	w.regions[start] = true
	if w.block == nil {
		return
	}
	iv := make([]byte, aes.BlockSize)
	binary.BigEndian.PutUint32(iv, uint32(start))
	region := w.buf[start : start+length]
	cipher.NewCTR(w.block, iv).XORKeyStream(region, region)
}
func (w *fb3Walk) str(pos int64) {
	s := w.follow(pos)
	n := w.u32(s)
	w.check(s+4, n+1)
	w.crypt(s+4, n)
}
func (w *fb3Walk) field(table, slot int64) int64 {
	vtable := table - w.i32(table)
	if slot+2 > w.u16(vtable) {
		return 0
	}
	if offset := w.u16(vtable + slot); offset != 0 {
		return table + offset
	}
	return 0
}
func (w *fb3Walk) enter(table int64, depth int) bool {
	if depth > 64 {
		w.fail("tables nested deeper than 64 levels")
	}
	if w.tables[table] {
		return false
	}
	w.tables[table] = true
	vtable := table - w.i32(table)
	w.check(vtable, 4)
	vtableSize, tableSize := w.u16(vtable), w.u16(vtable+2)
	if vtableSize < 4 || vtableSize&1 != 0 {
		w.fail("the buffer is malformed (bad vtable)")
	}
	w.check(vtable, vtableSize)
	w.check(table, tableSize)
	return true
}
func (w *fb3Walk) walk(index int, table int64, depth int) {
	if !w.enter(table, depth) {
		return
	}
	p := w.program
	at := p[1+index]
	ops := p[at]
	at++
	for op := 0; op < ops; op++ {
		kind, slot := p[at], int64(p[at+1])
		at += 2
		arg := 0
		switch kind {
		case 0, 2, 4, 5:
			arg = p[at]
			at++
		case 6, 7:
			w.fail("unions are not used by this driver")
		}
		loc := w.field(table, slot)
		if loc == 0 {
			continue
		}
		switch kind {
		case 0:
			w.check(loc, int64(arg))
			w.crypt(loc, int64(arg))
		case 1:
			w.str(loc)
		case 2:
			v := w.follow(loc)
			w.crypt(v+4, w.count(v, int64(arg))*int64(arg))
		case 3:
			v := w.follow(loc)
			n := w.count(v, 4)
			for i := int64(0); i < n; i++ {
				w.str(v + 4 + 4*i)
			}
		case 4:
			w.walk(arg, w.follow(loc), depth+1)
		case 5:
			v := w.follow(loc)
			n := w.count(v, 4)
			for i := int64(0); i < n; i++ {
				w.walk(arg, w.follow(v+4+4*i), depth+1)
			}
		}
	}
}

// fb3BufferKey is HKDF-SHA256(key, no salt, "flatbuffers-buffer-v3" || BE32(recordIndex)).
func fb3BufferKey(key []byte, recordIndex uint32) []byte {
	extract := hmac.New(sha256.New, make([]byte, sha256.Size))
	extract.Write(key)
	expand := hmac.New(sha256.New, extract.Sum(nil))
	info := []byte("flatbuffers-buffer-v3\x00\x00\x00\x00\x01")
	binary.BigEndian.PutUint32(info[21:], recordIndex)
	expand.Write(info)
	return expand.Sum(nil)
}

// fb3Crypt encrypts or decrypts (the same operation) buf in place.
func fb3Crypt(buf, key []byte, recordIndex uint32, program []int) (err error) {
	if len(key) != 32 {
		return fb3Err("FlatbuffersEncryption: the key must be 32 bytes")
	}
	defer func() {
		if r := recover(); r != nil {
			e, ok := r.(fb3Err)
			if !ok {
				panic(r)
			}
			err = e
		}
	}()
	root := int64(binary.LittleEndian.Uint32(buf))
	dry := &fb3Walk{buf: buf, program: program, tables: map[int64]bool{}, regions: map[int64]bool{}}
	dry.check(root, 4)
	dry.walk(0, root, 0)
	block, e := aes.NewCipher(fb3BufferKey(key, recordIndex))
	if e != nil {
		return e
	}
	w := &fb3Walk{buf: buf, program: program, block: block, tables: map[int64]bool{}, regions: map[int64]bool{}}
	w.walk(0, root, 0)
	return nil
}

