// Generates the FlatBuffers bindings of typed module frames that no pinned Go package carries yet:
//
//   node sdn-server/internal/typedfb/generate.mjs <space-data-module-sdk checkout> <spacedatastandards.org checkout>
//
// - flownotice/flownotice_generated.go: flatc --go of the SDK's schemas/runtime/FlowNotice.fbs (FNTC), the report a
//   module emits for unchanged/skipped/refused work (epoch-state's derive report).
// - wha/wha_generated.go: flatc --go --preserve-case (as SDS lib/go is generated) of SDS schema/WHA/main.fbs ($WHA, Wallet Holdings Attestation), a draft for
//   SDS 1.249.0. Once go.mod pins a spacedatastandards.org/lib/go release that carries WHA, import lib/go/WHA and
//   delete this package.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sdk = path.resolve(process.argv[2] || "");
const sds = path.resolve(process.argv[3] || "");
if (!fs.existsSync(path.join(sdk, "schemas/runtime/FlowNotice.fbs")) || !fs.existsSync(path.join(sds, "schema/WHA/main.fbs"))) {
  console.error("usage: node generate.mjs <space-data-module-sdk checkout> <spacedatastandards.org checkout>");
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const revision = (dir, sub) => {
  const rev = execFileSync("git", ["-C", dir, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
  const dirty = execFileSync("git", ["-C", dir, "status", "--porcelain", "--", sub], { encoding: "utf8" }).trim() !== "";
  return dirty ? `worktree ${path.basename(dir)} (uncommitted changes on ${rev})` : rev;
};

const { FlatcRunner } = await import(path.join(sdk, "node_modules/flatc-wasm/src/runner.mjs"));
const flatc = await FlatcRunner.init();

// One file per package: the package clause and imports once, then each type's declarations in `order`.
function write(pkg, generated, prefix, order, header) {
  const imports = new Set();
  const bodies = order.map((name) => {
    const source = generated[`${prefix}${name}.go`];
    if (!source) throw new Error(`flatc produced no ${prefix}${name}.go (has ${Object.keys(generated).join(", ")})`);
    let body = source.replace(/^\/\/ Code generated[^\n]*\n\n?/, "").replace(/^package \w+\n\n?/m, "");
    body = body.replace(/^import \(\n([\s\S]*?)\n\)\n\n?/m, (_, list) => { for (const l of list.split("\n")) if (l.trim()) imports.add(l.trim()); return ""; });
    body = body.replace(/^import ("[^"]+"|\w+ "[^"]+")\n\n?/m, (_, one) => { imports.add(one); return ""; });
    return body.trim();
  });
  const file = path.join(here, pkg, `${pkg}_generated.go`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${header}package ${pkg}\n\nimport (\n${[...imports].sort().map((l) => `\t${l}`).join("\n")}\n)\n\n${bodies.join("\n\n")}\n`);
  execFileSync("gofmt", ["-w", file]);
}

const notice = {};
for (const name of ["FlowNotice.fbs", "RuntimeCommon.fbs"]) notice[`/schemas/${name}`] = fs.readFileSync(path.join(sdk, "schemas/runtime", name), "utf8");
write("flownotice", flatc.generateCode({ entry: "/schemas/FlowNotice.fbs", files: notice }, "go", {}), "sdn/runtime/", ["flowNoticeKind", "FlowNotice"],
  `// Code generated by generate.mjs from space-data-module-sdk ${revision(sdk, "schemas/runtime")} (schemas/runtime/FlowNotice.fbs). DO NOT EDIT.\n\n`);

const wha = { "/schema/WHA/main.fbs": fs.readFileSync(path.join(sds, "schema/WHA/main.fbs"), "utf8") };
write("wha", flatc.generateCode({ entry: "/schema/WHA/main.fbs", files: wha }, "go", { preserveCase: true }), "", ["whaAssetKind", "WHAAccount", "WHAHolding", "WHAChain", "WHA"],
  `// Code generated by generate.mjs from spacedatastandards.org ${revision(sds, "schema/WHA")} (schema/WHA/main.fbs, draft for 1.249.0). DO NOT EDIT.\n\n`);
console.log(`typedfb: FlowNotice from module-sdk ${revision(sdk, "schemas/runtime")}, WHA from spacedatastandards.org ${revision(sds, "schema/WHA")}`);
