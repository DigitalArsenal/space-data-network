// Generates this package from a space-data-module-sdk checkout (typed contracts 1.0: hostcalls as SDS $PIV with
// HostOps aligned-binary records):
//
//   node sdn-server/internal/modulert/hostops/generate.mjs <module-sdk checkout>
//
// - hostops_aligned.go: flatc --go --aligned of the SDK's schemas/runtime/HostOps.fbs
// - registry.go: every record (size, alignment, view constructor), the enums, and the operation table (the SDK's
//   HOST_OPERATIONS: params / result records, raw and list ports, capability)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sdk = path.resolve(process.argv[2] || "");
if (!fs.existsSync(path.join(sdk, "schemas/runtime/HostOps.fbs"))) {
  console.error("usage: node generate.mjs <space-data-module-sdk checkout>");
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const sdkRev = execFileSync("git", ["-C", sdk, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
const header = `// Code generated by generate.mjs from space-data-module-sdk ${sdkRev} (schemas/runtime/HostOps.fbs). DO NOT EDIT.\n\n`;

const { FlatcRunner } = await import(path.join(sdk, "node_modules/flatc-wasm/src/runner.mjs"));
const flatc = await FlatcRunner.init();
const schema = fs.readFileSync(path.join(sdk, "schemas/runtime/HostOps.fbs"), "utf8");
const generated = flatc.generateCode({ entry: "/schemas/HostOps.fbs", files: { "/schemas/HostOps.fbs": schema } }, "go", { aligned: true });
const goSource = Object.values(generated).find((text) => text.includes("package aligned"));
if (!goSource) throw new Error("flatc produced no Go aligned source");
fs.writeFileSync(path.join(here, "hostops_aligned.go"), header + goSource.replace(/^\/\/ Auto-generated[^\n]*\n\/\/ DO NOT EDIT[^\n]*\n\n?/, "").replace("package aligned", "package hostops"));

const records = [...goSource.matchAll(/^type (\w+) struct \{\n\s+Buffer \[\]byte/gm)].map((m) => m[1]);
const enums = [...schema.matchAll(/enum\s+(\w+)\s*:\s*\w+\s*\{([^}]*)\}/g)].map((m) => [m[1], m[2].replace(/\/\/[^\n]*/g, "").split(",").map((v) => v.trim()).filter(Boolean)]);
const { HOST_OPERATIONS } = await import(path.join(sdk, "src/standards/runtimeContracts.js"));
const q = (s) => JSON.stringify(s);
const strings = (list) => `[]string{${list.map(q).join(", ")}}`;
const ports = (map) => `map[string]string{${Object.entries(map).map(([k, v]) => `${q(k)}: ${q(v)}`).join(", ")}}`;
let out = header + "package hostops\n\n";
out += "// Records is every HostOps aligned record by root type name.\nvar Records = map[string]RecordType{\n";
for (const name of records) out += `\t${q(name)}: {Name: ${q(name)}, Size: ${name}Size, Align: ${name}Align, View: func(b []byte, o int) any { return ${name}FromPointer(b, o) }},\n`;
out += "}\n\n// Enums names each HostOps enum's values in declaration order (value = index).\nvar Enums = map[string][]string{\n";
for (const [name, values] of enums) out += `\t${q(name)}: ${strings(values)},\n`;
out += "}\n\n// Operations is the SDK's HOST_OPERATIONS: every host operation's records, ports and capability.\nvar Operations = map[string]Operation{\n";
for (const [op, spec] of Object.entries(HOST_OPERATIONS)) {
  out += `\t${q(op)}: {Params: ${q(spec.params ?? "")}, Result: ${q(spec.result ?? "")}, Capability: ${q(spec.capability ?? "")}, ` +
    `RawIn: ${strings(spec.rawIn)}, RawOut: ${strings(spec.rawOut)}, ListsIn: ${ports(spec.listsIn)}, ListsOut: ${ports(spec.listsOut)}},\n`;
}
out += "}\n";
fs.writeFileSync(path.join(here, "registry.go"), out);
execFileSync("gofmt", ["-w", path.join(here, "hostops_aligned.go"), path.join(here, "registry.go")]);
console.log(`hostops: ${records.length} records, ${enums.length} enums, ${Object.keys(HOST_OPERATIONS).length} operations from module-sdk ${sdkRev}`);
