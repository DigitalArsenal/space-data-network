// Generates this package's FlatBuffers bindings from a space-data-module-sdk checkout: the module config a host hands
// a module (plugin.getConfig answers raw "config" with one ModuleConfig FlatBuffer, file identifier MCFG).
//
//   node sdn-server/internal/modulert/runtimecfg/generate.mjs <module-sdk checkout>
//
// - moduleconfig_generated.go: flatc --go of the SDK's schemas/runtime/ModuleConfig.fbs (ModuleConfig, ConfigEntry,
//   ConfigTable, configValueKind), one file, package runtimecfg. encode.go (hand-written) builds it from a node config.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sdk = path.resolve(process.argv[2] || "");
if (!fs.existsSync(path.join(sdk, "schemas/runtime/ModuleConfig.fbs"))) {
  console.error("usage: node generate.mjs <space-data-module-sdk checkout>");
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const sdkRev = execFileSync("git", ["-C", sdk, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
// A checkout with uncommitted changes (an SDK release in progress) is named as its worktree, not as the commit it
// sits on: the files are pinned to the release commit once it exists.
const sdkDirty = execFileSync("git", ["-C", sdk, "status", "--porcelain", "--", "schemas/runtime"], { encoding: "utf8" }).trim() !== "";
const sdkSource = sdkDirty ? `worktree ${path.basename(sdk)} (uncommitted changes on ${sdkRev}; to be pinned to the release commit)` : sdkRev;
const header = `// Code generated by generate.mjs from space-data-module-sdk ${sdkSource} (schemas/runtime/ModuleConfig.fbs). DO NOT EDIT.\n\n`;

const { FlatcRunner } = await import(path.join(sdk, "node_modules/flatc-wasm/src/runner.mjs"));
const flatc = await FlatcRunner.init();
const files = {};
for (const name of ["ModuleConfig.fbs", "RuntimeCommon.fbs"]) files[`/schemas/${name}`] = fs.readFileSync(path.join(sdk, "schemas/runtime", name), "utf8");
const generated = flatc.generateCode({ entry: "/schemas/ModuleConfig.fbs", files }, "go", {});
const order = ["configValueKind", "ConfigEntry", "ConfigTable", "ModuleConfig"];
const sources = order.map((name) => {
  const source = generated[`sdn/runtime/${name}.go`];
  if (!source) throw new Error(`flatc produced no sdn/runtime/${name}.go`);
  return source;
});
// one file: the package clause and imports once, then each type's declarations
const imports = new Set();
const bodies = sources.map((source) => {
  let body = source.replace(/^\/\/ Code generated[^\n]*\n\n?/, "").replace(/^package runtime\n\n?/m, "");
  body = body.replace(/^import \(\n([\s\S]*?)\n\)\n\n?/m, (_, list) => { for (const l of list.split("\n")) if (l.trim()) imports.add(l.trim()); return ""; });
  body = body.replace(/^import ("[^"]+")\n\n?/m, (_, one) => { imports.add(one); return ""; });
  return body.trim();
});
const out = `${header}package runtimecfg\n\nimport (\n${[...imports].sort().map((l) => `\t${l}`).join("\n")}\n)\n\n${bodies.join("\n\n")}\n`;
fs.writeFileSync(path.join(here, "moduleconfig_generated.go"), out);
execFileSync("gofmt", ["-w", path.join(here, "moduleconfig_generated.go")]);
console.log(`runtimecfg: ModuleConfig bindings from module-sdk ${sdkSource}`);
