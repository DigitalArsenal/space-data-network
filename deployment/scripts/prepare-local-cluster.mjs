#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const deployDir = resolve(scriptDir, '..');
const repoRoot = resolve(deployDir, '..');
const generatedDir = resolve(deployDir, 'generated');
const keyPath = resolve(generatedDir, 'node.key');
const sdnServerDir = resolve(repoRoot, 'sdn-server');

mkdirSync(generatedDir, { recursive: true });

const keygenOutput = execFileSync(
  'go',
  ['run', './cmd/sdn-keygen', '--out', keyPath, '--json'],
  {
    cwd: sdnServerDir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  },
);

const keygen = JSON.parse(keygenOutput);
const peerID = keygen.peerId;
if (typeof peerID !== 'string' || peerID.length === 0) {
  throw new Error('sdn-keygen did not return a peerId');
}

const bootstrapWsAddr = `/dns4/full-node-1/tcp/8080/ws/p2p/${peerID}`;
const bootstrapTcpAddr = `/dns4/full-node-1/tcp/4001/p2p/${peerID}`;

function writeFullNodeConfig(fileName, bootstrapAddrs) {
  const bootstrapYaml = bootstrapAddrs.map((addr) => `    - ${addr}`).join('\n');
  const contents = `mode: full

network:
  bootstrap:
${bootstrapYaml}

storage:
  path: /app/data
  max_size: 10GB
  gc_interval: 1h

admin:
  enabled: true
  listen_addr: 0.0.0.0:5001
  require_auth: true
  session_expiry: 24h
  totp_required: false
  tls_enabled: false
  frontend_path: /app/admin-ui
  admin_ui_path: /app/admin-ui
  webui_path: /app/webui

peers:
  registry_path: /app/data/peers.db

tor:
  enabled: false
  hidden_service_enabled: false

flows:
  enabled: false
  storage_path: /app/data/flows

setup:
  token_expiry: 10m
  data_path: /app/data
`;

  writeFileSync(resolve(generatedDir, fileName), contents, { mode: 0o644 });
}

writeFullNodeConfig('full-node-1.yaml', [bootstrapWsAddr]);
writeFullNodeConfig('full-node-2.yaml', [bootstrapWsAddr]);

writeFileSync(
  resolve(deployDir, '.env'),
  [
    '# Generated by deployment/scripts/prepare-local-cluster.mjs',
    `SDN_LOCAL_BOOTSTRAP_PEER_ID=${peerID}`,
    `SDN_LOCAL_BOOTSTRAP_WS_ADDR=${bootstrapWsAddr}`,
    `SDN_LOCAL_BOOTSTRAP_TCP_ADDR=${bootstrapTcpAddr}`,
    '',
  ].join('\n'),
  { mode: 0o644 },
);

console.log(`Prepared local cluster bootstrap peer ${peerID}`);
