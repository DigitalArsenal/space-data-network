function rectangularShape({
  azDeg,
  elDeg,
  xHalfAngleDeg,
  yHalfAngleDeg,
  maxRangeM,
  minRangeM = 0,
  minElDeg,
  maxElDeg,
  frame = "LOCAL_ENU",
}) {
  return {
    kind: "RECTANGULAR",
    frame,
    azDeg,
    elDeg,
    xHalfAngleDeg,
    yHalfAngleDeg,
    minRangeM,
    maxRangeM,
    minElevationDeg: minElDeg,
    maxElevationDeg: maxElDeg,
  };
}

function conicShape({
  azDeg,
  elDeg,
  outerHalfAngleDeg,
  innerHalfAngleDeg = 0,
  minClockAngleDeg = 0,
  maxClockAngleDeg = 360,
  maxRangeM,
  minRangeM = 0,
  minElDeg,
  maxElDeg,
  frame = "LOCAL_ENU",
}) {
  return {
    kind: "CONIC",
    frame,
    azDeg,
    elDeg,
    outerHalfAngleDeg,
    innerHalfAngleDeg,
    minClockAngleDeg,
    maxClockAngleDeg,
    minRangeM,
    maxRangeM,
    minElevationDeg: minElDeg,
    maxElevationDeg: maxElDeg,
  };
}

