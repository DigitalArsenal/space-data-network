#!/usr/bin/env node
// sync-anchors.mjs — make every trust site read deployment/identity/anchors.json.
//
//   node deployment/identity/sync-anchors.mjs           # write every derived copy
//   node deployment/identity/sync-anchors.mjs --check   # fail if any copy drifted
//   node deployment/identity/sync-anchors.mjs --from <owner anchors.json>
//        # ROTATION.md step 2: merge the owner's generated identity into the
//        # COMMITTED anchors.json, then write every derived copy
//
// anchors.json is the ONE source. Code in this repository reads it directly
// (anchors-lib.mjs) wherever it can; the places that cannot — a Go embed, the
// published sdn-js package, the packaged desktop app, the fleet trust file,
// YAML configs and docs — get a derived copy written here, and --check (run
// by scripts/oss-preflight.sh in CI and by anchors.test.mjs) fails when one
// differs. Cutting over to a new identity is therefore: replace anchors.json,
// run this script, release.
//
// Text mirrors are lines carrying an `identity-anchor: <kind>` marker; the
// value on that line is rewritten in place:
//   provider.bootstrap  <bootstrapTransports[0]>/p2p/<provider.peerId>
//   provider.browser    <browserTransports[0]>/p2p/<provider.peerId>
//   provider.peerId     <provider.peerId>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ANCHORS_PATH, loadAnchors, releaseProblems, structuralProblems } from './anchors-lib.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

export const COPY_TARGETS = [
  'sdn-server/internal/trustanchors/anchors.json',
  'desktop/src/common/identity-anchors.json',
];

export const TS_TARGET = 'sdn-js/src/identity-anchors.generated.ts';
export const FLEET_ROOTS_TARGET = 'deployment/release/fleet-trust-roots.json';

export const JSON_MIRRORS = [
  { file: 'deployment/module-placement.json', path: ['nodes', 'tu-delft', 'peerId'], kind: 'provider.peerId' },
];

export const TEXT_MIRRORS = [
  'deployment/celestrak/config.yaml',
  'deployment/config/servers.yaml',
  'deployment/remote/node.yaml.template',
  'sdn-server/deploy/README.md',
];

const MARKER = /identity-anchor:\s*(provider\.(?:bootstrap|browser|peerId))/;
const PEER_TOKEN = /(16Uiu2[1-9A-HJ-NP-Za-km-z]{40,}|PLACEHOLDER-SEC001-[A-Z0-9-]+)/;
const MULTIADDR_TOKEN = /\/(?:ip4|ip6|dns4|dns6|dns|dnsaddr)\/[^\s'"`,]+?\/p2p\/(?:16Uiu2[1-9A-HJ-NP-Za-km-z]{40,}|PLACEHOLDER-SEC001-[A-Z0-9-]+)/;

export function anchorValue(anchors, kind) {
  const p = anchors.provider;
  switch (kind) {
    case 'provider.peerId':
      return p.peerId;
    case 'provider.bootstrap':
      return `${p.bootstrapTransports[0]}/p2p/${p.peerId}`;
    case 'provider.browser':
      return `${p.browserTransports[0]}/p2p/${p.peerId}`;
    default:
      throw new Error(`unknown anchor kind ${kind}`);
  }
}

export function renderTypeScript(anchorsText) {
  const anchors = JSON.parse(anchorsText);
  return (
    '// GENERATED by deployment/identity/sync-anchors.mjs from deployment/identity/anchors.json.\n' +
    '// Do not edit: change anchors.json and re-run the script (its --check runs in CI).\n' +
    `export const IDENTITY_ANCHORS = ${JSON.stringify(anchors, null, 2)} as const;\n`
  );
}

export function renderFleetRoots(anchors) {
  return `${JSON.stringify(anchors.updateRoots)}\n`;
}

export function rewriteTextMirror(text, anchors) {
  let markers = 0;
  const lines = text.split('\n').map((line) => {
    const match = MARKER.exec(line);
    if (!match) return line;
    markers += 1;
    const kind = match[1];
    const value = anchorValue(anchors, kind);
    const token = kind === 'provider.peerId' ? PEER_TOKEN : MULTIADDR_TOKEN;
    if (!token.test(line)) throw new Error(`identity-anchor marker without a ${kind} value: ${line.trim()}`);
    return line.replace(token, value);
  });
  return { text: lines.join('\n'), markers };
}

function getPath(object, path) {
  return path.reduce((cursor, key) => (cursor == null ? undefined : cursor[key]), object);
}

/**
 * Rewrite one string value of a JSON file in place, keeping the file's own
 * formatting: the current value must occur exactly once, as a JSON string.
 */
export function rewriteJsonMirror(text, mirror, anchors) {
  const current = getPath(JSON.parse(text), mirror.path);
  if (typeof current !== 'string') throw new Error(`${mirror.file}: ${mirror.path.join('.')} is not a string`);
  const value = anchorValue(anchors, mirror.kind);
  if (current === value) return text;
  const quoted = JSON.stringify(current);
  if (text.split(quoted).length !== 2) throw new Error(`${mirror.file}: ${quoted} is not unique; cannot rewrite in place`);
  const rewritten = text.replace(quoted, JSON.stringify(value));
  if (getPath(JSON.parse(rewritten), mirror.path) !== value) throw new Error(`${mirror.file}: rewrite missed ${mirror.path.join('.')}`);
  return rewritten;
}

/** Every derived file's expected contents, keyed by repo-relative path. */
export function expectedOutputs(root = REPO_ROOT, anchorsPath = ANCHORS_PATH) {
  const anchorsText = readFileSync(anchorsPath, 'utf8');
  const anchors = JSON.parse(anchorsText);
  const out = new Map();
  for (const target of COPY_TARGETS) out.set(target, anchorsText);
  out.set(TS_TARGET, renderTypeScript(anchorsText));
  out.set(FLEET_ROOTS_TARGET, renderFleetRoots(anchors));
  for (const mirror of JSON_MIRRORS) {
    out.set(mirror.file, rewriteJsonMirror(readFileSync(join(root, mirror.file), 'utf8'), mirror, anchors));
  }
  for (const file of TEXT_MIRRORS) {
    const { text, markers } = rewriteTextMirror(readFileSync(join(root, file), 'utf8'), anchors);
    if (markers === 0) throw new Error(`${file} lost its identity-anchor markers`);
    out.set(file, text);
  }
  return out;
}

export function drift(root = REPO_ROOT, anchorsPath = ANCHORS_PATH) {
  const stale = [];
  for (const [file, contents] of expectedOutputs(root, anchorsPath)) {
    let current = null;
    try {
      current = readFileSync(join(root, file), 'utf8');
    } catch {
      // missing counts as drift
    }
    if (current !== contents) stale.push(file);
  }
  return stale;
}

// The provider fields the owner's generator fills in (new-node-identity.mjs
// mergeAnchors). Everything else in the committed file — the denylist, the
// other peers, transports — stays as committed.
export const OWNER_PROVIDER_FIELDS = Object.freeze([
  'peerId', 'identityPublicKey', 'xpub', 'signingPublicKey', 'encryptionPublicKey',
  'publisherPublicKey', 'x25519PublicKey', 'grantVerifierPublicKey', 'rootAdminPublicKey', 'discoveryCid',
]);

/**
 * Step 2 (verifier r3): `cp owner/anchors.json anchors.json` would silently drop
 * every denylist entry committed after the owner generated his file. Take ONLY
 * provider identity fields and updateRoots from the owner's file; keep the
 * committed file otherwise, and union the two denylists so nothing is lost.
 * Refuses a result that is not release-ready (placeholders, a denylisted or
 * non-separate root, an inconsistent identity).
 */
export function mergeOwnerAnchors(committed, owner) {
  const merged = JSON.parse(JSON.stringify(committed));
  for (const field of OWNER_PROVIDER_FIELDS) {
    if (typeof owner?.provider?.[field] !== 'string') throw new Error(`the owner's anchors.json has no provider.${field}`);
    merged.provider[field] = owner.provider[field];
  }
  if (!owner.updateRoots || typeof owner.updateRoots !== 'object') throw new Error("the owner's anchors.json has no updateRoots");
  merged.updateRoots = { ...owner.updateRoots };
  const ownDeny = owner.denylist || {};
  for (const [key, values] of Object.entries(merged.denylist)) {
    if (!Array.isArray(values)) continue;
    for (const value of ownDeny[key] || []) if (!values.includes(value)) values.push(value);
  }
  merged.status = JSON.stringify(merged).includes('"PLACEHOLDER-') ? 'placeholder' : 'released';
  const problems = releaseProblems(merged);
  if (problems.length) throw new Error(`the merged anchors are not release-ready:\n  ${problems.join('\n  ')}`);
  return merged;
}

function main(argv) {
  const check = argv.includes('--check');
  const fromIndex = argv.indexOf('--from');
  if (fromIndex >= 0) {
    const ownerPath = argv[fromIndex + 1];
    if (!ownerPath) throw new Error('--from needs the owner anchors.json');
    const merged = mergeOwnerAnchors(loadAnchors(), loadAnchors(resolve(ownerPath)));
    writeFileSync(ANCHORS_PATH, `${JSON.stringify(merged, null, 2)}\n`);
    console.log(`[sync-anchors] merged provider identity and updateRoots from ${ownerPath}; the committed denylist is kept`);
  }
  const anchors = loadAnchors();
  const problems = structuralProblems(anchors);
  if (problems.length) {
    console.error(`[sync-anchors] anchors.json is unsound:\n  ${problems.join('\n  ')}`);
    return 1;
  }
  if (check) {
    const stale = drift();
    if (stale.length) {
      console.error('[sync-anchors] these files do not match deployment/identity/anchors.json:');
      for (const file of stale) console.error(`    - ${file}`);
      console.error('Run: node deployment/identity/sync-anchors.mjs');
      return 1;
    }
    console.log(`[sync-anchors] OK: every derived copy matches anchors.json (status: ${anchors.status})`);
    return 0;
  }
  for (const [file, contents] of expectedOutputs()) writeFileSync(join(REPO_ROOT, file), contents);
  console.log(`[sync-anchors] wrote the derived copies of anchors.json (status: ${anchors.status})`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
