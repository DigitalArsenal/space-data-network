#!/usr/bin/env bash
#
# sdn-overlay.sh — enumerate, and PROVE, the SDN overlay on upstream kubo.
#
# The kubo module in this repo is pristine upstream github.com/ipfs/kubo with a
# thin SDN overlay on top. This tool makes that claim falsifiable:
#
#   list    Print the overlay manifest: every SDN-ADDED path plus the few
#           upstream files the overlay MODIFIES, with counts.
#   verify  Take a PRISTINE upstream kubo straight out of git (the kubo subtree
#           at the commit BEFORE the first SDN commit on this branch), apply the
#           SDN overlay onto it, build it with build-sdn-kubo.sh, and confirm the
#           SDN plugins are compiled in. Reports touched-upstream vs SDN-added
#           counts — the "slight modification of upstream kubo" proof.
#   regen   Regenerate sdn-overlay.manifest from the working tree (dev helper).
#
# Manifest format (sdn-overlay.manifest), paths are kubo-module-relative:
#   A <path>   SDN-added file  (absent in pristine upstream kubo)
#   M <path>   upstream file MODIFIED by the overlay
#
# No heavy deps: git + coreutils + build-sdn-kubo.sh.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MANIFEST="$SCRIPT_DIR/sdn-overlay.manifest"
MANIFEST_REL="sdn/build/sdn-overlay.manifest"   # this file's own module-relative path
BUILDER="$SCRIPT_DIR/build-sdn-kubo.sh"

# kubo module root is two levels up from kubo/sdn/build.
MODULE_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPO_ROOT="$(git -C "$MODULE_ROOT" rev-parse --show-toplevel)"
# kubo dir name relative to the repo root (normally "kubo").
KUBO_PREFIX="$(git -C "$MODULE_ROOT" rev-parse --show-prefix)"; KUBO_PREFIX="${KUBO_PREFIX%/}"

# Roots that are 100% additive: they do not exist in pristine upstream kubo, so
# every file under them is an SDN addition.
SDN_ADD_ROOTS=(sdn plugin/plugins/sdnflag plugin/plugins/sdnruntime plugin/plugins/sdnapi)
# The upstream files the overlay is expected to touch (the "small known patch set").
EXPECTED_MODIFIED=(go.mod go.sum plugin/loader/preload.go plugin/loader/preload_list)

log()  { printf '[sdn-overlay] %s\n' "$*" >&2; }
die()  { printf '[sdn-overlay] ERROR: %s\n' "$*" >&2; exit 1; }

# Resolve the pristine upstream ref: parent of the first commit on this branch
# that introduces any SDN path.
resolve_pristine() {
  local first
  local -a paths=()
  local r
  for r in "${SDN_ADD_ROOTS[@]}"; do paths+=("$KUBO_PREFIX/$r"); done
  first="$(git -C "$REPO_ROOT" log --reverse --format=%H -- "${paths[@]}" | head -1)"
  [[ -n "$first" ]] || die "could not find the first SDN commit (no history under ${SDN_ADD_ROOTS[*]})"
  git -C "$REPO_ROOT" rev-parse "${first}^"
}

# --- regen -------------------------------------------------------------------
cmd_regen() {
  local pristine; pristine="$(resolve_pristine)"
  log "pristine upstream ref: $pristine"

  local -a add_globs=()
  local r
  for r in "${SDN_ADD_ROOTS[@]}"; do add_globs+=("$r"); done

  # ADDED: every tracked-or-untracked (non-ignored) file under the additive
  # roots, taken from the working tree so newly-authored files are included.
  local added
  added="$(cd "$MODULE_ROOT" && git ls-files --cached --others --exclude-standard -- "${add_globs[@]}")"
  # Always include this manifest itself (it may not exist on disk on first run).
  added="$(printf '%s\n%s\n' "$added" "$MANIFEST_REL" | sed '/^$/d' | sort -u)"

  # MODIFIED: upstream files that differ between pristine and the working tree,
  # excluding anything under the additive roots.
  local modified
  modified="$(git -C "$REPO_ROOT" diff --name-only --diff-filter=M "$pristine" -- "$KUBO_PREFIX/" \
              | sed "s#^$KUBO_PREFIX/##")"
  # Drop any modified path that lives under an additive root (defensive).
  local filtered=""
  local p keep
  while IFS= read -r p; do
    [[ -z "$p" ]] && continue
    keep=1
    for r in "${SDN_ADD_ROOTS[@]}"; do [[ "$p" == "$r/"* ]] && keep=0; done
    [[ $keep -eq 1 ]] && filtered+="$p"$'\n'
  done <<< "$modified"
  modified="$(printf '%s' "$filtered" | sed '/^$/d' | sort -u)"

  {
    echo "# SDN overlay manifest — generated by sdn-overlay.sh regen."
    echo "# Paths are kubo-module-relative. A = SDN-added, M = upstream-modified."
    echo "# Pristine upstream ref used at generation time: $pristine"
    while IFS= read -r p; do [[ -n "$p" ]] && echo "M $p"; done <<< "$modified"
    while IFS= read -r p; do [[ -n "$p" ]] && echo "A $p"; done <<< "$added"
  } > "$MANIFEST"

  local na nm
  na="$(grep -c '^A ' "$MANIFEST" || true)"
  nm="$(grep -c '^M ' "$MANIFEST" || true)"
  log "wrote $MANIFEST: $nm modified-upstream, $na SDN-added"
}

# --- list --------------------------------------------------------------------
cmd_list() {
  [[ -f "$MANIFEST" ]] || die "manifest missing: $MANIFEST (run: sdn-overlay.sh regen)"
  local na nm
  nm="$(grep -c '^M ' "$MANIFEST" || true)"
  na="$(grep -c '^A ' "$MANIFEST" || true)"
  echo "== Upstream files MODIFIED by the SDN overlay ($nm) =="
  grep '^M ' "$MANIFEST" | sed 's/^M /  /' | sort
  echo
  echo "== SDN-ADDED files ($na) =="
  grep '^A ' "$MANIFEST" | sed 's/^A /  /' | sort
  echo
  echo "Total: $nm modified + $na added (out of $(git -C "$REPO_ROOT" ls-files "$KUBO_PREFIX" | wc -l | tr -d ' ') tracked kubo files)."
}

# --- verify ------------------------------------------------------------------
cmd_verify() {
  [[ -f "$MANIFEST" ]] || die "manifest missing: $MANIFEST (run: sdn-overlay.sh regen)"
  [[ -x "$BUILDER" ]] || die "builder missing/not executable: $BUILDER"

  local pristine; pristine="$(resolve_pristine)"
  log "pristine upstream ref : $pristine  ($(git -C "$REPO_ROOT" log -1 --format=%s "$pristine"))"

  # (1) Cross-check the manifest against the real git delta pristine..HEAD.
  local git_mod git_add
  git_mod="$(git -C "$REPO_ROOT" diff --name-only --diff-filter=M "$pristine" HEAD -- "$KUBO_PREFIX/" | sed "s#^$KUBO_PREFIX/##" | sort)"
  git_add="$(git -C "$REPO_ROOT" diff --name-only --diff-filter=A "$pristine" HEAD -- "$KUBO_PREFIX/" | sed "s#^$KUBO_PREFIX/##" | sort)"
  local man_mod man_add
  man_mod="$(grep '^M ' "$MANIFEST" | sed 's/^M //' | sort)"
  man_add="$(grep '^A ' "$MANIFEST" | sed 's/^A //' | sort)"

  if [[ "$git_mod" != "$man_mod" ]]; then
    log "MANIFEST DRIFT (modified set) — manifest vs git diff pristine..HEAD:"
    diff <(printf '%s\n' "$man_mod") <(printf '%s\n' "$git_mod") >&2 || true
    die "manifest modified-set does not match git; run: sdn-overlay.sh regen"
  fi
  # Added: git delta must be a subset of the manifest (manifest also lists its
  # own path + build scripts which are all legitimately SDN-added).
  local missing
  missing="$(comm -23 <(printf '%s\n' "$git_add") <(printf '%s\n' "$man_add"))"
  if [[ -n "$missing" ]]; then
    log "MANIFEST DRIFT (added set) — files added in git but absent from manifest:"
    printf '  %s\n' $missing >&2
    die "manifest added-set is incomplete; run: sdn-overlay.sh regen"
  fi

  # (2) The modified-upstream set must equal the small known patch set.
  local expected; expected="$(printf '%s\n' "${EXPECTED_MODIFIED[@]}" | sort)"
  if [[ "$man_mod" != "$expected" ]]; then
    log "WARNING: modified-upstream set differs from the expected small patch set:"
    log "  expected: ${EXPECTED_MODIFIED[*]}"
    log "  actual  : $(printf '%s ' $man_mod)"
    log "  the 'slight modification' claim may need review."
  fi

  local n_mod n_add
  n_mod="$(printf '%s\n' "$man_mod" | sed '/^$/d' | wc -l | tr -d ' ')"
  n_add="$(printf '%s\n' "$man_add" | sed '/^$/d' | wc -l | tr -d ' ')"

  # (3) Materialize pristine upstream kubo from git into a temp module root.
  # WORK is global so the EXIT trap can still see it after this function returns.
  WORK="$(mktemp -d "${TMPDIR:-/tmp}/sdn-overlay.XXXXXX")"
  trap 'rm -rf "${WORK:-}"' EXIT
  log "materializing pristine upstream kubo -> $WORK"
  git -C "$REPO_ROOT" archive "$pristine" "$KUBO_PREFIX" | tar -x -C "$WORK"
  local pmod="$WORK/$KUBO_PREFIX"
  [[ -f "$pmod/go.mod" ]] || die "pristine extract failed (no go.mod at $pmod)"

  # Sanity: pristine really is plain upstream (no SDN dirs).
  local r
  for r in "${SDN_ADD_ROOTS[@]}"; do
    [[ -e "$pmod/$r" ]] && die "pristine tree already contains SDN path '$r' — wrong ref?"
  done
  log "pristine confirmed clean (no SDN paths present)"

  # (4) Apply the overlay: copy every manifest path from the working tree on top.
  local applied=0 p
  while IFS= read -r p; do
    [[ -z "$p" ]] && continue
    [[ -f "$MODULE_ROOT/$p" ]] || die "overlay source missing: $MODULE_ROOT/$p"
    mkdir -p "$pmod/$(dirname "$p")"
    cp -p "$MODULE_ROOT/$p" "$pmod/$p"
    applied=$((applied + 1))
  done < <(cat <(printf '%s\n' "$man_mod") <(printf '%s\n' "$man_add") | sed '/^$/d')
  log "applied overlay: $applied files copied onto pristine tree"

  # (5) Prove the SDN plugins are wired in the overlaid tree.
  local pl="$pmod/plugin/loader/preload.go"
  for want in pluginsdnflag pluginsdnruntime pluginsdnapi; do
    grep -q "$want" "$pl" || die "overlay preload.go missing plugin registration: $want"
  done
  grep -q 'replace github.com/DigitalArsenal/spacedatastandards.org/lib/go => ./sdn/third_party/spacedatastandards-go' "$pmod/go.mod" \
    || die "overlay go.mod missing SDN replace directive"
  log "SDN plugin registrations present in overlaid preload.go (sdnflag, sdnruntime, sdnapi)"

  # (6) Build the overlaid pristine tree with the canonical builder.
  local out="$WORK/ipfs-overlay"
  log "building overlaid pristine kubo with build-sdn-kubo.sh ..."
  "$BUILDER" --module-root "$pmod" --out "$out" >&2
  [[ -x "$out" ]] || die "build did not produce a binary at $out"
  local ver; ver="$("$out" --version 2>&1 | head -1)"
  log "overlaid binary boots: $ver"

  echo
  echo "================= SDN OVERLAY VERIFY: PASS ================="
  echo "pristine upstream kubo ref : $pristine"
  echo "upstream files MODIFIED    : $n_mod  ($(printf '%s ' $man_mod))"
  echo "SDN files ADDED            : $n_add"
  echo "overlay applied + built    : yes  ($applied files copied)"
  echo "SDN plugins compiled in    : sdnflag, sdnruntime, sdnapi"
  echo "binary                     : $ver"
  echo "==========================================================="
  echo "Proof: a pristine upstream kubo checkout needs only $n_mod upstream-file"
  echo "edits + $n_add added files to become SDN-kubo. That is the 'slight"
  echo "modification of upstream kubo' thesis, demonstrated end-to-end."
}

usage() { sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

case "${1:-}" in
  list)   cmd_list ;;
  verify) cmd_verify ;;
  regen)  cmd_regen ;;
  -h|--help|help|"") usage ;;
  *) die "unknown command: $1 (use list|verify|regen)" ;;
esac
