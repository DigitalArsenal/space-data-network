#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "..");
const MANIFEST_PATH = path.join(REPO_ROOT, "suite.versions.json");
const TS_OUTPUT_PATH = path.join(REPO_ROOT, "sdn-js", "src", "version-info.generated.ts");
const GO_OUTPUT_PATH = path.join(REPO_ROOT, "sdn-server", "internal", "versioninfo", "generated.go");
const CHECK_MODE = process.argv.includes("--check");

// The kubo fork in-repo is the single source of truth for the Kubo version
// the node is based on (kubo/version.go CurrentVersionNumber) — read it,
// never duplicate it into the manifest.
function readKuboVersion() {
  const src = fs.readFileSync(path.join(REPO_ROOT, "kubo", "version.go"), "utf8");
  const m = src.match(/CurrentVersionNumber\s*=\s*"([^"]+)"/);
  if (!m) throw new Error("kubo/version.go: CurrentVersionNumber not found");
  return m[1];
}

function readManifest() {
  const raw = fs.readFileSync(MANIFEST_PATH, "utf8");
  const manifest = JSON.parse(raw);
  validateManifest(manifest);
  return manifest;
}

function validateManifest(manifest) {
  const requiredStrings = [
    ["suiteVersion", manifest.suiteVersion],
    ["dependencies.spacedatastandards", manifest.dependencies?.spacedatastandards],
    ["dependencies.flatsql", manifest.dependencies?.flatsql],
    ["dependencies.hdWalletWasm", manifest.dependencies?.hdWalletWasm],
    ["dependencies.hdWalletUI", manifest.dependencies?.hdWalletUI],
    ["dependencies.ipfsWebUI", manifest.dependencies?.ipfsWebUI],
    ["advertisement.currentFlag", manifest.advertisement?.currentFlag],
    ["updates.defaultChannel", manifest.updates?.defaultChannel],
  ];

  for (const [key, value] of requiredStrings) {
    if (typeof value !== "string" || value.trim() === "") {
      throw new Error(`suite.versions.json is missing required string field: ${key}`);
    }
  }

  if (!Array.isArray(manifest.advertisement?.supportedFlags) || manifest.advertisement.supportedFlags.length === 0) {
    throw new Error("suite.versions.json must define advertisement.supportedFlags");
  }

  if (!manifest.advertisement.supportedFlags.includes(manifest.advertisement.currentFlag)) {
    throw new Error("advertisement.currentFlag must appear in advertisement.supportedFlags");
  }
}

function escapeForTS(value) {
  return JSON.stringify(String(value));
}

function escapeForGo(value) {
  return JSON.stringify(String(value));
}

function renderTS(manifest) {
  const supportedFlags = manifest.advertisement.supportedFlags
    .map((flag) => `  ${escapeForTS(flag)},`)
    .join("\n");

  return `// Code generated by scripts/generate-suite-version-info.js. DO NOT EDIT.

export const SUITE_VERSION = ${escapeForTS(manifest.suiteVersion)};
export const SPACEDATASTANDARDS_VERSION = ${escapeForTS(manifest.dependencies.spacedatastandards)};
export const FLATSQL_VERSION = ${escapeForTS(manifest.dependencies.flatsql)};
export const HD_WALLET_WASM_VERSION = ${escapeForTS(manifest.dependencies.hdWalletWasm)};
export const HD_WALLET_UI_VERSION = ${escapeForTS(manifest.dependencies.hdWalletUI)};
export const IPFS_WEBUI_VERSION = ${escapeForTS(manifest.dependencies.ipfsWebUI)};
export const KUBO_VERSION = ${escapeForTS(manifest.kuboVersion)};
export const DEFAULT_UPDATE_CHANNEL = ${escapeForTS(manifest.updates.defaultChannel)};
export const CURRENT_ADVERTISEMENT_FLAG = ${escapeForTS(manifest.advertisement.currentFlag)};
export const SUPPORTED_ADVERTISEMENT_FLAGS = [
${supportedFlags}
] as const;

export const SUITE_VERSION_INFO = Object.freeze({
  suiteVersion: SUITE_VERSION,
  spacedatastandardsVersion: SPACEDATASTANDARDS_VERSION,
  flatsqlVersion: FLATSQL_VERSION,
  hdWalletWasmVersion: HD_WALLET_WASM_VERSION,
  hdWalletUIVersion: HD_WALLET_UI_VERSION,
  ipfsWebUIVersion: IPFS_WEBUI_VERSION,
  defaultUpdateChannel: DEFAULT_UPDATE_CHANNEL,
  currentAdvertisementFlag: CURRENT_ADVERTISEMENT_FLAG,
  supportedAdvertisementFlags: [...SUPPORTED_ADVERTISEMENT_FLAGS],
});
`;
}

function renderGo(manifest) {
  const supportedFlags = manifest.advertisement.supportedFlags
    .map((flag) => `\t${escapeForGo(flag)},`)
    .join("\n");

  return `// Code generated by scripts/generate-suite-version-info.js. DO NOT EDIT.

package versioninfo

const (
\tSuiteVersion = ${escapeForGo(manifest.suiteVersion)}
\tSpaceDataStandardsVersion = ${escapeForGo(manifest.dependencies.spacedatastandards)}
\tFlatSQLVersion = ${escapeForGo(manifest.dependencies.flatsql)}
\tHDWalletWasmVersion = ${escapeForGo(manifest.dependencies.hdWalletWasm)}
\tHDWalletUIVersion = ${escapeForGo(manifest.dependencies.hdWalletUI)}
\tIPFSWebUIVersion = ${escapeForGo(manifest.dependencies.ipfsWebUI)}
\tKuboVersion = ${escapeForGo(manifest.kuboVersion)}
\tDefaultUpdateChannel = ${escapeForGo(manifest.updates.defaultChannel)}
\tCurrentAdvertisementFlag = ${escapeForGo(manifest.advertisement.currentFlag)}
)

var SupportedAdvertisementFlags = []string{
${supportedFlags}
}

func CopySupportedAdvertisementFlags() []string {
\treturn append([]string(nil), SupportedAdvertisementFlags...)
}
`;
}

function writeFile(targetPath, content) {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  if (CHECK_MODE) {
    const existing = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, "utf8") : null;
    if (existing !== content) {
      throw new Error(`${path.relative(REPO_ROOT, targetPath)} is out of date; run node scripts/generate-suite-version-info.js`);
    }
    return;
  }
  fs.writeFileSync(targetPath, content, "utf8");
}

function main() {
  const manifest = readManifest();
  manifest.kuboVersion = readKuboVersion();
  writeFile(TS_OUTPUT_PATH, renderTS(manifest));
  writeFile(GO_OUTPUT_PATH, renderGo(manifest));
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
