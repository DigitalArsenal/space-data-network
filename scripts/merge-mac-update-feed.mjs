#!/usr/bin/env node
/**
 * merge-mac-update-feed.mjs <dir>
 *
 * electron-updater reads exactly ONE channel file per platform: on macOS that
 * is latest-mac.yml, and it picks the architecture from WITHIN that file —
 * MacUpdater.js filters `files` by whether the url contains "arm64", and when
 * no arm64 entry exists an Apple Silicon Mac silently takes the x64 build and
 * runs it under Rosetta.
 *
 * The two macOS legs build on different runners (arm64 on macos-14, x64 on
 * macos-15-intel), so electron-builder writes a latest-mac.yml on each that
 * lists only its own arch, and the release job's download with
 * merge-multiple:true lets one overwrite the other. v1.0.5-beta.69 shipped the
 * x64 one: the release carried mac-arm64.dmg and mac-arm64.zip while its
 * latest-mac.yml offered only mac-x64, so every Apple Silicon install would
 * have updated itself onto the Intel build.
 *
 * So each macOS leg names its channel file latest-mac-<arch>.yml, and this
 * merges them into the single latest-mac.yml electron-updater will ask for.
 *
 * The file is generated by a pinned electron-builder and has a fixed shape —
 * a `files:` sequence of indented entries between top-level keys — so this
 * splices that one block rather than depending on a YAML parser the release
 * runner does not have. It then re-reads its own output and fails unless every
 * input url survived, so a shape change cannot pass silently.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';

const TOP_LEVEL = /^[^\s#]/;

/** The lines of the `files:` block, excluding the `files:` line itself. */
export function filesBlock(text) {
  const lines = text.split('\n');
  const start = lines.findIndex((line) => line === 'files:');
  if (start === -1) throw new Error('no `files:` key');
  const rest = lines.slice(start + 1);
  let end = rest.findIndex((line) => TOP_LEVEL.test(line));
  if (end === -1) end = rest.length;
  const block = rest.slice(0, end).filter((line) => line.trim() !== '');
  if (block.length === 0) throw new Error('`files:` block is empty');
  return block;
}

export function urls(text) {
  return [...text.matchAll(/^\s*-?\s*url:\s*(\S+)\s*$/gm)].map((m) => m[1]);
}

/**
 * Merge `extra` feeds into `base`, keeping base's own header, top-level
 * path/sha512 and releaseDate. Only the `files:` block grows.
 */
export function mergeFeeds(base, extra) {
  const seen = new Set(urls(base));
  const additions = [];
  for (const feed of extra) {
    let keep = false;
    for (const line of filesBlock(feed)) {
      const match = /^\s*-\s*url:\s*(\S+)\s*$/.exec(line);
      if (match) keep = !seen.has(match[1]);
      if (keep) additions.push(line);
      if (match && keep) seen.add(match[1]);
    }
  }
  if (additions.length === 0) return base;
  const lines = base.split('\n');
  const start = lines.indexOf('files:');
  const rest = lines.slice(start + 1);
  let end = rest.findIndex((line) => TOP_LEVEL.test(line));
  if (end === -1) end = rest.length;
  const insertAt = start + 1 + end;
  return [...lines.slice(0, insertAt), ...additions, ...lines.slice(insertAt)].join('\n');
}

function main(dir) {
  const parts = readdirSync(dir)
    .filter((name) => /^latest-mac-[A-Za-z0-9_]+\.yml$/.test(name))
    .sort();
  if (parts.length === 0) {
    // Not "nothing to do": if no channel file reaches the release, macOS
    // auto-update stops working for everyone, silently, and the artifact list
    // still looks complete. Only an already-merged feed is an acceptable
    // reason to find no per-arch parts.
    if (existsSync(join(dir, 'latest-mac.yml'))) {
      console.log('[mac-feed] latest-mac.yml already present, nothing to merge');
      return;
    }
    console.error(`[mac-feed] no latest-mac*.yml in ${dir}: the release would ship no macOS update feed`);
    process.exit(1);
  }
  // x64 stays the BASE so the legacy top-level path/sha512 keeps pointing at
  // the build that runs on every Mac; `files` is what modern updaters read,
  // and that is where arm64 has to appear.
  const x64 = parts.find((name) => name.includes('x64')) ?? parts[0];
  const others = parts.filter((name) => name !== x64);
  const base = readFileSync(join(dir, x64), 'utf8');
  const merged = mergeFeeds(base, others.map((name) => readFileSync(join(dir, name), 'utf8')));

  const want = new Set([...urls(base), ...others.flatMap((name) => urls(readFileSync(join(dir, name), 'utf8')))]);
  const got = new Set(urls(merged));
  const missing = [...want].filter((url) => !got.has(url));
  if (missing.length > 0) {
    console.error(`[mac-feed] merge dropped: ${missing.join(', ')}`);
    process.exit(1);
  }
  if (![...got].some((url) => url.includes('arm64'))) {
    console.error('[mac-feed] merged feed lists no arm64 file; Apple Silicon would update onto x64');
    process.exit(1);
  }

  writeFileSync(join(dir, 'latest-mac.yml'), merged);
  for (const name of parts) unlinkSync(join(dir, name));
  console.log(`[mac-feed] latest-mac.yml lists ${got.size} file(s): ${[...got].join(', ')}`);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: merge-mac-update-feed.mjs <dir>');
    process.exit(1);
  }
  main(dir);
}
